using Content.Client.Administration.Managers;
using Content.Shared.Administration;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.SS220.AntagRemoval.UI;

[GenerateTypedNameReferences]
public sealed partial class AntagRemovalControl : BoxContainer
{
    private readonly IClientAdminManager _adminManager;
    private PlayerInfo? _selectedPlayer;
    private AntagRemovalWindow? _window;

    public AntagRemovalControl()
    {
        RobustXamlLoader.Load(this);
        _adminManager = IoCManager.Resolve<IClientAdminManager>();
        RemoveButton.OnPressed += OnOpenRoles;
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();
        _adminManager.AdminStatusUpdated += OnAdminStatusUpdated;
        OnAdminStatusUpdated();
    }

    protected override void ExitedTree()
    {
        _adminManager.AdminStatusUpdated -= OnAdminStatusUpdated;
        _window?.Close();
        base.ExitedTree();
    }

    public void SetPlayer(PlayerInfo? player)
    {
        _window?.Close();
        _selectedPlayer = player;
        RemoveButton.Disabled = player is not { Connected: true } || !_adminManager.HasFlag(AdminFlags.Admin);
    }

    private void OnAdminStatusUpdated()
    {
        SetPlayer(_selectedPlayer);
    }

    private void OnOpenRoles(BaseButton.ButtonEventArgs args)
    {
        if (_selectedPlayer is not { Connected: true } player || !_adminManager.HasFlag(AdminFlags.Admin))
            return;

        _window?.Close();
        _window = new AntagRemovalWindow(player);
        _window.OnClose += () => _window = null;
        _window.OpenCentered();
        _window.RequestRoles();
    }
}
