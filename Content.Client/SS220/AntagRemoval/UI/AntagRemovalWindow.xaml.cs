using Content.Client.Administration.Managers;
using Content.Shared.Administration;
using Content.Shared.SS220.AntagRemoval;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.SS220.AntagRemoval.UI;

[GenerateTypedNameReferences]
public sealed partial class AntagRemovalWindow : DefaultWindow
{
    private readonly IClientAdminManager _adminManager;
    private readonly AntagRemovalSystem _removal;
    private readonly PlayerInfo _player;
    private Guid _requestId;
    private NetEntity? _body;
    private NetEntity? _mind;

    public AntagRemovalWindow(PlayerInfo player)
    {
        RobustXamlLoader.Load(this);
        _adminManager = IoCManager.Resolve<IClientAdminManager>();
        _removal = IoCManager.Resolve<IEntityManager>().System<AntagRemovalSystem>();
        _player = player;
        TargetLabel.Text = $"{player.CharacterName} ({player.Username})";
        TargetLabel.ToolTip = TargetLabel.Text;
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();
        _removal.RolesReceived += OnRolesReceived;
        _adminManager.AdminStatusUpdated += OnAdminStatusUpdated;
    }

    protected override void ExitedTree()
    {
        _requestId = Guid.Empty;
        _removal.RolesReceived -= OnRolesReceived;
        _adminManager.AdminStatusUpdated -= OnAdminStatusUpdated;
        base.ExitedTree();
    }

    public void RequestRoles()
    {
        if (!_adminManager.HasFlag(AdminFlags.Admin))
        {
            Close();
            return;
        }

        BeginRequest();
        _removal.RequestRoles(_requestId, _player.SessionId);
    }

    private void OnAdminStatusUpdated()
    {
        if (!_adminManager.HasFlag(AdminFlags.Admin))
            Close();
    }

    private void BeginRequest()
    {
        _requestId = Guid.NewGuid();
        RoleButtons.RemoveAllChildren();
        _body = null;
        _mind = null;
        ShowStatus(Loc.GetString("ss220-removeantag-ui-waiting"));
    }

    private void ShowStatus(string message)
    {
        StatusLabel.Text = message;
        StatusLabel.ToolTip = message;
        StatusLabel.Visible = message.Length > 0;
    }

    private void OnRolesReceived(RemovableRolesEvent ev)
    {
        if (_requestId == Guid.Empty || ev.RequestId != _requestId || _player.SessionId != ev.Target ||
            !_adminManager.HasFlag(AdminFlags.Admin))
            return;

        _requestId = Guid.Empty;
        _body = ev.Body;
        _mind = ev.Mind;
        RoleButtons.RemoveAllChildren();
        var hasRoles = ev.Roles.Count > 0 || ev.UnsupportedRoles.Count > 0;
        ShowStatus(ev.Message.Length > 0 || hasRoles
            ? ev.Message
            : Loc.GetString("ss220-removeantag-ui-empty"));

        foreach (var (kind, roleName) in ev.Roles)
        {
            var button = new RemoveAntagRoleButton(kind, roleName)
            {
                Disabled = _body == null || _mind == null
            };
            button.OnPressed += OnRemoveRole;
            RoleButtons.AddChild(button);
        }

        foreach (var roleName in ev.UnsupportedRoles)
        {
            var button = new RemoveAntagRoleButton(string.Empty, roleName)
            {
                Disabled = true,
                ToolTip = Loc.GetString("ss220-removeantag-ui-unsupported")
            };
            RoleButtons.AddChild(button);
        }
    }

    private void OnRemoveRole(BaseButton.ButtonEventArgs args)
    {
        if (_requestId != Guid.Empty || _body is not { } body || _mind is not { } mind ||
            args.Button is not RemoveAntagRoleButton { Disabled: false } button ||
            !_adminManager.HasFlag(AdminFlags.Admin))
            return;

        var kind = button.Kind;
        BeginRequest();
        _removal.RequestRemoval(_requestId, _player.SessionId, body, mind, kind);
    }
}
