[GenerateTypedNameReferences]
public sealed partial class ConnectionLogsWindow : DefaultWindow
{
    public event Action? OnNext;
    public event Action<string>? OnSearch;
    private bool _loading;

    public ConnectionLogsWindow()
    {
        RobustXamlLoader.Load(this);
        NextButton.OnPressed += _ =>
        {
            if (_loading)
                return;

            SetLoading(true);
            OnNext?.Invoke();
        };
        SearchButton.OnPressed += _ => Search();
        CkeyInput.OnTextEntered += _ => Search();
    }

    private void Search()
    {
        if (_loading)
            return;

        SetLoading(true);
        OnSearch?.Invoke(CkeyInput.Text);
    }

    private void SetLoading(bool loading)
    {
        _loading = loading;
        CkeyInput.Editable = !loading;
        SearchButton.Disabled = loading;
        if (loading)
            NextButton.Disabled = true;
    }

    public void SetState(ConnectionLogsEuiState state)
    {
        TargetLabel.Text = Loc.GetString("connection-logs-target", ("ckey", state.Ckey));
        CkeyInput.Text = state.Ckey;
        SetLoading(state.IsLoading);
        StatusLabel.Text = state.IsLoading
            ? Loc.GetString("connection-logs-loading")
            : state.Error != null
                ? Loc.GetString(state.Error)
                : string.Empty;
        if (state.IsLoading)
            return;

        LogsContainer.DisposeAllChildren();
        var rowIndex = 0;

        foreach (var log in state.Logs)
        {
            var denied = log.DeniedReason == null
                ? Loc.GetString("connection-logs-allowed")
                : Loc.GetString("connection-logs-denied", ("reason", log.DeniedReason));
            var server = log.ServerName ?? Loc.GetString("connection-logs-unknown-server");

            var row = new GridContainer
            {
                Columns = 6,
                HorizontalExpand = true
            };
            row.AddChild(CreateCell(log.Time.ToString(), 170));
            row.AddChild(CreateCell(log.UserName, 150));
            row.AddChild(CreateCell(log.Address, 150));
            row.AddChild(CreateCell(denied, 170));
            row.AddChild(CreateCell(server, 150));
            row.AddChild(CreateCell(log.Trust.ToString("0.###", CultureInfo.InvariantCulture), 90));

            var rowPanel = new PanelContainer
            {
                HorizontalExpand = true,
                Margin = new Thickness(0, 1)
            };
            rowPanel.AddStyleClass(rowIndex % 2 == 0 ? "BackgroundPanel" : "BackgroundDark");
            rowPanel.AddChild(row);
            LogsContainer.AddChild(rowPanel);
            rowIndex++;
        }

        if (state.Logs.Count == 0 && state.Error == null)
        {
            LogsContainer.AddChild(new Label
            {
                Text = Loc.GetString(state.Ckey.Length == 0 ? "connection-logs-prompt" : "connection-logs-empty"),
                HorizontalAlignment = HAlignment.Center
            });
        }

        NextButton.Disabled = state.IsLoading || !state.HasNext;
        NextButton.Text = state.IsLoading
            ? Loc.GetString("connection-logs-loading")
            : Loc.GetString("connection-logs-next");
    }

    private static Label CreateCell(string text, int minWidth)
    {
        return new Label
        {
            Text = text,
            MinWidth = minWidth,
            HorizontalExpand = true,
            VerticalAlignment = VAlignment.Center,
            ClipText = true,
            Margin = new Thickness(8, 5)
        };
    }

