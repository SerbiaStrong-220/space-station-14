using Content.Shared.Database.SS220.PendingBans;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.SS220.Administration.PendingBans;

[GenerateTypedNameReferences]
public sealed partial class PendingBanControl : BoxContainer
{
    public event Action? ScheduleChanged;

    public bool IsPending => Enabled.Pressed;

    public PendingBanControl()
    {
        RobustXamlLoader.Load(this);
        Trigger.AddItem(Loc.GetString("pending-ban-delay"), (int)PendingBanTrigger.Delay);
        Trigger.AddItem(Loc.GetString("pending-ban-round-end"), (int)PendingBanTrigger.RoundEnd);
        Trigger.AddItem(Loc.GetString("pending-ban-round-start"), (int)PendingBanTrigger.RoundStart);
        Trigger.AddItem(Loc.GetString("pending-ban-lobby"), (int)PendingBanTrigger.Lobby);
        Trigger.SelectId((int)PendingBanTrigger.Delay);
        Delay.ToolTip = Loc.GetString("pending-ban-delay-help", ("maxDelay", PendingBanData.MaxDelayMinutes));
        Enabled.OnToggled += _ =>
        {
            Options.Visible = IsPending;
            ScheduleChanged?.Invoke();
        };
        Trigger.OnItemSelected += args =>
        {
            Trigger.SelectId(args.Id);
            DelayRow.Visible = args.Id == (int)PendingBanTrigger.Delay;
            ScheduleChanged?.Invoke();
        };
        Delay.OnTextChanged += _ =>
        {
            Delay.ModulateSelfOverride = null;
            ScheduleChanged?.Invoke();
        };
    }

    public bool TryGetSchedule(out PendingBanTrigger trigger, out uint minutes)
    {
        trigger = IsPending ? (PendingBanTrigger)Trigger.SelectedId : PendingBanTrigger.Immediate;
        minutes = 0;
        if (trigger != PendingBanTrigger.Delay)
            return true;

        if (uint.TryParse(Delay.Text, out minutes) && minutes is > 0 and <= PendingBanData.MaxDelayMinutes)
            return true;

        Delay.ModulateSelfOverride = Color.Red;
        Delay.GrabKeyboardFocus();
        return false;
    }
}
