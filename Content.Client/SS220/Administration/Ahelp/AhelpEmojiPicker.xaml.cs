using System.Linq;
using Content.Shared.SS220.Administration.Ahelp;
using Robust.Client.AutoGenerated;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client.SS220.Administration.Ahelp;

[GenerateTypedNameReferences]
public sealed partial class AhelpEmojiPicker : Popup
{
    [Dependency] private IPrototypeManager _prototypes = default!;
    [Dependency] private IResourceCache _resources = default!;

    public event Action<string>? EmojiSelected;

    public AhelpEmojiPicker()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);

        foreach (var emoji in _prototypes.EnumeratePrototypes<AhelpEmojiPrototype>()
                     .OrderBy(emoji => emoji.ID, StringComparer.OrdinalIgnoreCase))
        {
            var button = new AhelpEmojiButton(emoji, _resources);
            button.OnPressed += _ => EmojiSelected?.Invoke(emoji.Shortcode);
            EmojiGrid.AddChild(button);
        }
    }
}
