using Content.Shared.SS220.DarkForces.Ratvar.Prototypes;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.SS220.DarkForces.Ratvar.Structures;

[GenerateTypedNameReferences]
public sealed partial class RatvarWorkshopRecipeControl : Control
{
    public event Action? OnCraftPressed;

    public RatvarWorkshopRecipeControl(RatvarCraftReceiptPrototype recipe, SpriteSystem sprites, bool disabled)
    {
        RobustXamlLoader.Load(this);
        RecipeIcon.Texture = sprites.Frame0(recipe.Icon);
        RecipeButton.Text = recipe.Name;
        RecipeButton.ToolTip = recipe.Name;
        RecipeButton.Disabled = disabled;
        CostLabel.SetMessage(Loc.GetString("ratvar-workshop-recipe-cost",
            ("brass", recipe.BrassCost), ("power", recipe.PowerCost)));
        RecipeButton.OnPressed += _ => OnCraftPressed?.Invoke();
    }
}
