using Robust.Shared.Timing;

namespace Content.Client.SS220.Silicon.UI;

[GenerateTypedNameReferences]
public sealed partial class SiliconComponentsMenu : FancyWindow
{
    [Dependency] private IEntityManager _entity = default!;
    private PowerCellSystem _powerCell;
    private SharedBatterySystem _battery;

    public Action? OpticsButtonPressed;
    public Action? ServoButtonPressed;
    public Action? BrainButtonPressed;
    public Action? SpineButtonPressed;
    public Action? DriveButtonPressed;
    public Action? EjectBatteryButtonPressed;
    public Action<EntityUid>? RemoveModuleButtonPressed;

    private List<EntityUid> _modules = new();

    public EntityUid Entity;

    public SiliconComponentsMenu()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        ButtonDict[PartType.Brain] = BrainButton;
        ButtonDict[PartType.Drive] = DriveButton;
        ButtonDict[PartType.Optics] = OpticsButton;
        ButtonDict[PartType.Spine] = SpineButton;
        ButtonDict[PartType.Servo] = ServoButton;

        _powerCell = _entity.System<PowerCellSystem>();
        _battery = _entity.System<SharedBatterySystem>();

        EjectBatteryButton.OnPressed += _ => EjectBatteryButtonPressed?.Invoke();
        OpticsButton.OnPressed += _ => OpticsButtonPressed?.Invoke();
        ServoButton.OnPressed += _ => ServoButtonPressed?.Invoke();
        BrainButton.OnPressed += _ => BrainButtonPressed?.Invoke();
        SpineButton.OnPressed += _ => SpineButtonPressed?.Invoke();
        DriveButton.OnPressed += _ => DriveButtonPressed?.Invoke();

        OpticsButton.TexturePath = "/Textures/Interface/Minimalist/SlotBackground.png";
        ServoButton.TexturePath = "/Textures/Interface/Minimalist/SlotBackground.png";
        BrainButton.TexturePath = "/Textures/Interface/Minimalist/SlotBackground.png";
        SpineButton.TexturePath = "/Textures/Interface/Minimalist/SlotBackground.png";
        DriveButton.TexturePath = "/Textures/Interface/Minimalist/SlotBackground.png";
    }

    public readonly Dictionary<PartType, TextureButton> ButtonDict = new Dictionary<PartType, TextureButton>();

    public void SetEntity(EntityUid entity)
    {
        Entity = entity;

        BorgSprite.SetEntity(entity);

        UpdateBatteryButton();
        UpdateButtons();
        UpdateModulePanel();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        FixedPoint2 charge = 0f;

        FixedPoint2 chargeMax = 0f;

        FixedPoint2 chargeFraction = 0f;

        if (_powerCell.TryGetBatteryFromSlot(Entity, out var battery))
        {
            charge = _battery.GetCharge(battery.Value.AsNullable());
            chargeMax = battery.Value.Comp.MaxCharge;
            chargeFraction = charge / chargeMax;
        }

        BatteryCharge.Text = Loc.GetString("synth-battery-charge", ("amount", charge), ("percentage", chargeFraction));
        BatteryCharge.FontColorOverride = Color.DarkGreen;
        BatteryChargeMax.Text = Loc.GetString("synth-battery-charge-max", ("amount", chargeMax));
        BatteryChargeMax.FontColorOverride = Color.DarkGreen;
    }

    public void UpdateBatteryButton()
    {
        EjectBatteryButton.Disabled = !_powerCell.HasBattery(Entity);
    }

    public void UpdateButtons()
    {
        if (!_entity.TryGetComponent(Entity, out SiliconComponentsComponent? comp))
            return;

        foreach (var button in ButtonDict.Keys)
        {
            SpriteView? buttonView = null;

            foreach (var child in ButtonDict[button].Children)
            {
                if (child is SpriteView childView)
                {
                    buttonView = childView;
                    break;
                }
            }

            if (buttonView == null)
                return;

            if (ButtonDict[button] == null)
                continue;

            if (comp.Parts.TryGetValue(button, out var part) && part.ContainedEntity is { Valid: true } partValid)
            {
                //ButtonDict[button].Text = _entity.GetComponent<MetaDataComponent>(partValid).EntityName;

                buttonView.SetEntity(partValid);
                buttonView.Visible = true;

                continue;
            }

            buttonView.Visible = false;
            ButtonDict[button].RemoveStyleClass(StyleClass.ButtonOpenLeft);
        }
    }

    public void UpdateModulePanel()
    {
        if (!_entity.TryGetComponent(Entity, out BorgChassisComponent? chassis))
            return;

        ModuleCounter.Text = Loc.GetString("borg-ui-module-counter",
            ("actual", chassis.ModuleCount),
            ("max", chassis.MaxModules));

        if (chassis.ModuleContainer.Count == _modules.Count)
        {
            var isSame = true;
            foreach (var module in chassis.ModuleContainer.ContainedEntities)
            {
                if (_modules.Contains(module))
                    continue;
                isSame = false;
                break;
            }

            if (isSame)
                return;
        }

        ModuleContainer.Children.Clear();
        _modules.Clear();
        foreach (var module in chassis.ModuleContainer.ContainedEntities)
        {
            var moduleComponent = _entity.GetComponent<BorgModuleComponent>(module);
            var control = new SiliconModuleControl(module, _entity, !moduleComponent.DefaultModule);
            control.RemoveButtonPressed += () =>
            {
                RemoveModuleButtonPressed?.Invoke(module);
            };
            ModuleContainer.AddChild(control);
            _modules.Add(module);
        }
    }
}
