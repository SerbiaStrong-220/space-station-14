using System.Numerics;
using Content.Client.Message;
using Content.Client.Resources;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.SS220.Photography.UI;
[GenerateTypedNameReferences]
public sealed partial class PhotoWindow : BaseWindow
{
    [Dependency] private IResourceCache _resources = default!;

    public PhotoWindow()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);

        // Keep the original paper frame independent of the active UI stylesheet.
        var border = new StyleBoxTexture
        {
            Texture = _resources.GetTexture("/Textures/Interface/Paper/paper_background_default.svg.96dpi.png"),
            Modulate = Color.White
        };
        border.SetPatchMargin(StyleBox.Margin.All, 16f);
        PhotoBackground.PanelOverride = border;
        LoadingBackground.PanelOverride = new StyleBoxFlat(Color.Black);

        CloseButton.OnPressed += _ => Close();
    }

    public void SetBackText(string? text)
    {
        BackText.SetMarkup(text ?? "");
    }

    /// <summary>
    /// The visualizer owns this shared texture; the BUI holds its request until the window closes.
    /// </summary>
    public void SetTexture(Texture? texture)
    {
        if (Disposed)
            return;

        PhotoViewStatic.Texture = texture;
        PhotoViewStatic.Visible = texture != null;
        if (texture == null)
            LoadingTextLabel.Text = Loc.GetString("photo-failed-text-label");
    }

    protected override void Dispose(bool disposing)
    {
        if (disposing)
            PhotoViewStatic.Texture = null;

        base.Dispose(disposing);
    }

    // Drag by grabbing anywhere
    protected override DragMode GetDragModeFor(Vector2 relativeMousePos)
    {
        return DragMode.Move;
    }
}
