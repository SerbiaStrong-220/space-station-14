using System.Numerics;
using Content.Shared.SS220.CartridgeLoader.Cartridges;
using Content.Shared.SS220.Messenger;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client.SS220.Cartridges.Messenger;

[GenerateTypedNameReferences]
public sealed partial class MessengerUiFragment : BoxContainer
{
    private const int ReplyPreviewLength = 50;

    // the scroll bar learns its range only after a layout pass, so the scroll is applied a couple of frames later
    private const int ScrollToBottomFrames = 2;

    public event Action<ChatUid, string, MessageUid?>? OnMessageSendButtonPressed;
    public event Action<ChatUid>? OnHistoryViewPressed;
    public event Action? OnBackButtonPressed;
    public event Action? OnRefreshPressed;

    public ChatUid CurrentChat;

    public string? SearchString
    {
        get => _searchString;
        set => _searchString = value?.ToLower();
    }
    private string? _searchString;

    private int _scrollToBottomFrames;
    private MessageUid? _replyToId;

    public MessengerUiFragment()
    {
        RobustXamlLoader.Load(this);

        SendButton.OnPressed += _ => SendMessage();
        MessageInput.OnTextEntered += _ => SendMessage();
        BackButton.OnPressed += _ => OnBackButtonPressed?.Invoke();
        RefreshButton.OnPressed += _ => OnRefreshPressed?.Invoke();
        CancelReplyButton.OnPressed += _ => ClearReply();
        EmojiButton.OnToggled += args => EmojiPanel.Visible = args.Pressed;

        EmojiButton.Label.FontOverride = EmojiGrid.EmojiFont;
        EmojiButton.Text = MessengerEmoji.All[0].Symbol;
        EmojiGrid.OnEmojiPicked += code =>
        {
            MessageInput.InsertAtCursor(code);
            MessageInput.GrabKeyboardFocus();
        };
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (_scrollToBottomFrames <= 0)
            return;

        _scrollToBottomFrames--;
        ChatsScroll.SetScrollValue(new Vector2(0, float.MaxValue));
    }

    private void SendMessage()
    {
        var text = MessageInput.Text.Trim();

        if (text == "")
            return;

        OnMessageSendButtonPressed?.Invoke(CurrentChat, text, _replyToId);
        MessageInput.Clear();
        ClearReply();
    }

    public void UpdateChatsState(MessengerUiState messengerUiState)
    {
        ChatsContainer.RemoveAllChildren();

        var chats = new List<MessengerChatUiState>();

        foreach (var chat in messengerUiState.Chats.Values)
        {
            if (SearchString == null || ChatName(messengerUiState, chat).ToLower().Contains(SearchString))
                chats.Add(chat);
        }

        chats.Sort((a, b) => CompareChats(messengerUiState, a, b));

        foreach (var chat in chats)
        {
            var peer = GetPeer(messengerUiState, chat);
            var openedChat = chat;

            ChatsContainer.AddChild(new MessengerUiChatItem(ChatName(messengerUiState, chat),
                LastMessagePreview(messengerUiState, chat),
                _ =>
                {
                    ClearReply();
                    CurrentChat = openedChat.Id;
                    OnHistoryViewPressed?.Invoke(openedChat.Id);
                },
                chat.Unread,
                peer == null ? null : StatusColor(peer.Status),
                StatusText(peer)));
        }

        if (chats.Count == 0)
            ChatsContainer.AddChild(new Label { Text = Loc.GetString("messenger-ui-no-chats"), Align = Label.AlignMode.Center });

        SetChatView(false);
    }

    /// <summary>
    /// Favorites first, then chats with the most recent messages, then chats without messages by name.
    /// </summary>
    private static int CompareChats(MessengerUiState state, MessengerChatUiState a, MessengerChatUiState b)
    {
        var favoritesA = IsFavorites(state, a);

        if (favoritesA != IsFavorites(state, b))
            return favoritesA ? -1 : 1;

        if (a.LastMessage != b.LastMessage)
        {
            if (a.LastMessage == null)
                return 1;

            if (b.LastMessage == null)
                return -1;

            return b.LastMessage.Value.CompareTo(a.LastMessage.Value);
        }

        return string.Compare(ChatName(state, a), ChatName(state, b), StringComparison.CurrentCultureIgnoreCase);
    }

    private static bool IsFavorites(MessengerUiState state, MessengerChatUiState chat)
    {
        return chat.Kind == MessengerChatKind.Contact
               && chat.Members.Count == 1
               && chat.Members.Contains(state.ClientContact.Id);
    }

    private static string LastMessagePreview(MessengerUiState state, MessengerChatUiState chat)
    {
        if (chat.LastMessage == null || !state.Messages.TryGetValue(chat.LastMessage.Value, out var message))
            return "";

        if (message.FromContactId == state.ClientContact.Id)
            return Loc.GetString("messenger-ui-you-prefix", ("text", message.Text));

        if (chat.Kind == MessengerChatKind.Contact)
            return message.Text;

        // in a group chat it is not clear who wrote the message without a name
        return $"{SenderName(state, message)}: {message.Text}";
    }

    private static string ChatName(MessengerUiState state, MessengerChatUiState chat)
    {
        return GetPeer(state, chat)?.Name ?? chat.Name;
    }

    /// <summary>
    /// The other member of a personal chat, or null for other chats and if the contact is not known yet.
    /// </summary>
    private static MessengerContact? GetPeer(MessengerUiState state, MessengerChatUiState chat)
    {
        if (chat.Kind != MessengerChatKind.Contact)
            return null;

        foreach (var memberId in chat.Members)
        {
            if (memberId != state.ClientContact.Id && state.Contacts.TryGetValue(memberId, out var contact))
                return contact;
        }

        return null;
    }

    private static Color StatusColor(MessengerContactStatus status)
    {
        return status switch
        {
            MessengerContactStatus.Online => Color.LimeGreen,
            MessengerContactStatus.Cryo => Color.DodgerBlue,
            _ => Color.Gray,
        };
    }

    /// <summary>
    /// Note about the contact, or null if it is online.
    /// </summary>
    private static string? StatusText(MessengerContact? contact)
    {
        return contact?.Status switch
        {
            MessengerContactStatus.OutOfRange => Loc.GetString("messenger-contact-status-out-of-range"),
            MessengerContactStatus.Cryo => Loc.GetString("messenger-contact-status-cryo"),
            _ => null,
        };
    }

    public void UpdateChatHistoryState(MessengerUiState state)
    {
        ChatsContainer.RemoveAllChildren();

        if (state.Chats.TryGetValue(CurrentChat, out var chat))
        {
            var messageIds = new List<MessageUid>(chat.Messages);
            messageIds.Sort();

            var peer = GetPeer(state, chat);

            foreach (var messageId in messageIds)
            {
                if (!state.Messages.TryGetValue(messageId, out var message))
                    continue;

                if (SearchString != null && !message.Text.ToLower().Contains(SearchString))
                    continue;

                string? quoteSender = null;
                string? quoteText = null;

                if (message.ReplyToId != null && state.Messages.TryGetValue(message.ReplyToId.Value, out var quoted))
                {
                    quoteSender = SenderName(state, quoted);
                    quoteText = quoted.Text;
                }

                var isOwn = message.FromContactId == state.ClientContact.Id;

                ChatsContainer.AddChild(new MessengerUiMessageItem(message.Text,
                    message.Time,
                    isOwn || chat.Kind == MessengerChatKind.Contact ? null : SenderName(state, message),
                    isOwn,
                    null,
                    quoteSender,
                    quoteText,
                    () => SetReply(SenderName(state, message), message)));
            }

            if (ChatsContainer.ChildCount == 0)
                ChatsContainer.AddChild(new Label { Text = Loc.GetString("messenger-ui-no-messages"), Align = Label.AlignMode.Center });

            var statusText = StatusText(peer);
            var chatName = ChatName(state, chat);
            ChatNameLabel.Text = statusText == null ? chatName : $"{chatName} ({statusText})";
        }

        SetChatView(true);
        _scrollToBottomFrames = ScrollToBottomFrames;
    }

    private static string SenderName(MessengerUiState state, MessengerMessage message)
    {
        if (message.FromContactId == state.ClientContact.Id)
            return Loc.GetString("messenger-ui-you");

        return state.Contacts.TryGetValue(message.FromContactId, out var contact) ? contact.Name ?? "" : "";
    }

    private void SetReply(string senderName, MessengerMessage message)
    {
        _replyToId = message.Id;
        ReplyBar.Visible = true;
        ReplyLabel.SetMessage(MessengerEmoji.Format(MessengerEmoji.Preview($"{senderName}: {message.Text}", ReplyPreviewLength)),
            null,
            Color.LightGray);
        MessageInput.GrabKeyboardFocus();
    }

    private void ClearReply()
    {
        _replyToId = null;
        ReplyBar.Visible = false;
    }

    public void DisplayError(string err)
    {
        ChatsContainer.RemoveAllChildren();

        SetChatView(false);
        ChatsSearch.Visible = false;
        RefreshButton.Visible = true;
        ErrorLabel.Visible = true;
        ErrorLabel.Text = err;
    }

    /// <summary>
    /// Switches the controls between the chat list and the history of one chat.
    /// </summary>
    private void SetChatView(bool inChat)
    {
        BackButton.Visible = inChat;
        ChatNameLabel.Visible = inChat;
        HeaderSpacer.Visible = !inChat;
        InputRow.Visible = inChat;
        ReplyBar.Visible = inChat && _replyToId != null;
        EmojiPanel.Visible = inChat && EmojiButton.Pressed;
        ChatsSearch.Visible = true;
        ErrorLabel.Visible = false;
    }
}
