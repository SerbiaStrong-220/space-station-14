using Content.Client.RichText;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.SS220.Cartridges.Messenger;

[GenerateTypedNameReferences]
public sealed partial class MessengerUiChatItem : BoxContainer
{
    private const int MaxPreviewLength = 40;

    /// <param name="lastMessage">Preview text, may contain emoji shortcodes.</param>
    /// <param name="statusColor">Color of the dot before the name, the dot is hidden if null.</param>
    /// <param name="statusText">Short note about the contact, e.g. "out of range".</param>
    public MessengerUiChatItem(string chatName,
        string lastMessage,
        Action<BaseButton.ButtonEventArgs> onPressedOpenChatHistory,
        int unread,
        Color? statusColor,
        string? statusText)
    {
        RobustXamlLoader.Load(this);

        ChatName.Text = chatName;

        StatusDot.Visible = statusColor != null;
        StatusDot.FontColorOverride = statusColor;

        StatusLabel.Visible = statusText != null;
        StatusLabel.Text = statusText;
        StatusLabel.FontColorOverride = Color.Gray;

        var hasUnread = unread > 0;
        ChatName.FontColorOverride = hasUnread ? Color.White : null;
        LastMessage.SetMessage(MessengerEmoji.Format(MessengerEmoji.Preview(lastMessage, MaxPreviewLength)),
            UserFormattableTags.BaseAllowedTags,
            hasUnread ? Color.LightGray : Color.Gray);

        UnreadBadge.Visible = hasUnread;
        UnreadBadge.PanelOverride = new StyleBoxFlat { BackgroundColor = Color.FromHex("#c0392b") };
        UnreadLabel.Text = unread > 99 ? "99+" : unread.ToString();

        OpenChatHistoryButton.OnPressed += onPressedOpenChatHistory;
    }

    public MessengerUiChatItem()
    {
        RobustXamlLoader.Load(this);
    }
}
