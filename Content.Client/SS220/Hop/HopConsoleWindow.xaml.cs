using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared.SS220.Hop;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.SS220.Hop;

[GenerateTypedNameReferences]
public sealed partial class HopConsoleWindow : FancyWindow
{
    private readonly HopConsoleBoundUserInterface _owner;
    private HopConsoleState? _state;
    private HopJobEntry? _editing;
    private uint? _selectedRecord;
    private readonly List<string> _jobIds = new();
    private bool _loading;
    private bool _dirty;
    private HopConsoleOperation? _pending;

    public HopConsoleWindow(HopConsoleBoundUserInterface owner)
    {
        RobustXamlLoader.Load(this);
        _owner = owner;
        NewJob.Filterable = true;
        Tabs.SetTabTitle(0, Loc.GetString("hop-console-jobs-tab"));
        Tabs.SetTabTitle(1, Loc.GetString("hop-console-records-tab"));
        JobSearch.OnTextChanged += _ => PopulateJobs();
        RecordSearch.OnTextChanged += _ => PopulateRecords();
        RefreshButton.OnPressed += _ => _owner.Refresh();
        Slots.OnTextChanged += _ => JobChanged();
        Unlimited.OnToggled += _ => JobChanged();
        Priority.OnToggled += _ => JobChanged();
        DecreaseSlots.OnPressed += _ => AdjustSlots(-1);
        IncreaseSlots.OnPressed += _ => AdjustSlots(1);
        SaveJob.OnPressed += _ => Save();
        ResetJob.OnPressed += _ => SelectJob(_editing?.Id);
        NewRecord.OnPressed += _ => ShowRecordForm(true);
        CancelNewRecord.OnPressed += _ => ShowRecordForm(false);
        NewName.OnTextChanged += _ => UpdateButtons();
        NewTitle.OnTextChanged += _ => UpdateButtons();
        NewJob.OnItemSelected += args =>
        {
            NewJob.SelectId(args.Id);
            UpdateButtons();
        };
        AddRecord.OnPressed += _ =>
        {
            if (AddRecord.Disabled || NewJob.SelectedId < 0 || NewJob.SelectedId >= _jobIds.Count)
                return;
            Begin(HopConsoleOperation.AddRecord);
            _owner.AddRecord(NewName.Text.Trim(), _jobIds[NewJob.SelectedId], NewTitle.Text.Trim());
        };
        DeleteRecord.OnPressed += _ => DeleteConfirmation.Visible = true;
        CancelDelete.OnPressed += _ => DeleteConfirmation.Visible = false;
        ConfirmDelete.OnPressed += _ =>
        {
            if (_selectedRecord is not { } id || _pending != null)
                return;
            Begin(HopConsoleOperation.RemoveRecord);
            _owner.RemoveRecord(id);
        };
        UpdateButtons();
    }

    public void UpdateState(HopConsoleState state)
    {
        var jobsChanged = _state == null || !_state.Jobs.Select(JobSnapshot).SequenceEqual(state.Jobs.Select(JobSnapshot));
        var recordsChanged = _state == null || !_state.Records.Select(RecordSnapshot).SequenceEqual(state.Records.Select(RecordSnapshot));
        _state = state;
        StationName.Text = state.Available ? state.StationName : Loc.GetString("hop-console-no-station");
        DebugWarning.Visible = state.DebugJobs;
        if (!state.Available)
            SetStatus("hop-console-no-station", true);

        // Preserve an in-progress record and selected job when any other record changes.
        if (!_jobIds.SequenceEqual(state.Jobs.Select(j => j.Id)))
        {
            var selected = NewJob.SelectedId >= 0 && NewJob.SelectedId < _jobIds.Count
                ? _jobIds[NewJob.SelectedId] : null;
            NewJob.Clear();
            _jobIds.Clear();
            foreach (var job in state.Jobs)
            {
                NewJob.AddItem(job.Name, _jobIds.Count);
                _jobIds.Add(job.Id);
            }
            if (_jobIds.Count > 0)
                NewJob.SelectId(Math.Max(0, selected == null ? 0 : _jobIds.IndexOf(selected)));
        }

        var current = state.Jobs.FirstOrDefault(j => j.Id == _editing?.Id);
        if (_editing == null || current == null)
            SelectJob(state.Jobs.FirstOrDefault()?.Id);
        else if (jobsChanged && !_dirty && _pending == null)
            SelectJob(current.Id);
        else
            Current.Text = FormatSlots(current.AvailableSlots);

        if (jobsChanged)
            PopulateJobs();
        if (recordsChanged)
            PopulateRecords();
        if (_selectedRecord is { } id && !state.Records.Any(r => r.Key == id))
        {
            _selectedRecord = null;
            DeleteConfirmation.Visible = false;
            UpdateRecordDetails();
        }
        else
            UpdateRecordDetails();
        UpdateButtons();
    }

    public void HandleResult(HopConsoleResultMessage result)
    {
        _pending = null;
        SetStatus(result.Text, !result.Success);
        if (result.Operation == HopConsoleOperation.SaveJob && result.Success)
            SelectJob(_editing?.Id);
        if (result.Operation == HopConsoleOperation.AddRecord && result.Success)
        {
            NewName.Text = string.Empty;
            NewTitle.Text = string.Empty;
            ShowRecordForm(false);
        }
        if (result.Operation == HopConsoleOperation.RemoveRecord && result.Success)
            SelectRecord(null);
        UpdateButtons();
    }

    private void PopulateJobs()
    {
        JobList.RemoveAllChildren();
        var jobs = _state?.Jobs.Where(j => Matches(j.Name, JobSearch.Text)).ToList() ?? new();
        JobCount.Text = Loc.GetString("hop-console-job-count", ("count", jobs.Count));
        foreach (var job in jobs)
        {
            var button = ListButton(job.Name,
                Loc.GetString(job.Priority ? "hop-console-job-summary-priority" : "hop-console-job-summary",
                    ("slots", FormatSlots(job.AvailableSlots))), job.Id == _editing?.Id);
            button.OnPressed += _ =>
            {
                if (_pending != null)
                    return;
                if (_dirty)
                {
                    SetStatus("hop-console-unsaved", true);
                    return;
                }
                SelectJob(job.Id);
            };
            JobList.AddChild(button);
        }
        if (jobs.Count == 0)
            JobList.AddChild(new Label { Text = Loc.GetString("hop-console-no-jobs") });
    }

    private void PopulateRecords()
    {
        RecordList.RemoveAllChildren();
        var records = _state?.Records.Where(r => Matches(r.Name, RecordSearch.Text) ||
            Matches(r.JobTitle, RecordSearch.Text)).ToList() ?? new();
        RecordCount.Text = Loc.GetString("hop-console-record-count", ("count", records.Count));
        foreach (var record in records)
        {
            var button = ListButton(record.Name, record.JobTitle, record.Key == _selectedRecord);
            button.OnPressed += _ =>
            {
                if (_pending == null)
                    SelectRecord(record.Key);
            };
            RecordList.AddChild(button);
        }
        if (records.Count == 0)
            RecordList.AddChild(new Label { Text = Loc.GetString("hop-console-no-records") });
    }

    private static Button ListButton(string name, string subtitle, bool selected)
    {
        var button = new Button { ToggleMode = true, Pressed = selected, HorizontalExpand = true };
        var box = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, Margin = new Thickness(8, 6) };
        box.AddChild(new Label { Text = name, ClipText = true, ToolTip = name });
        box.AddChild(new Label { Text = subtitle, ClipText = true, ToolTip = subtitle, FontColorOverride = Color.FromHex("#9DAAB8") });
        button.AddChild(box);
        return button;
    }

    private void SelectJob(string? id)
    {
        _editing = _state?.Jobs.FirstOrDefault(j => j.Id == id);
        _dirty = false;
        JobDetails.Visible = _editing != null;
        JobEmpty.Visible = _editing == null;
        if (_editing is { } job)
        {
            _loading = true;
            JobName.Text = job.Name;
            RoundStart.Text = FormatSlots(job.RoundStartSlots);
            Configured.Text = FormatSlots(job.ConfiguredSlots);
            Current.Text = FormatSlots(job.AvailableSlots);
            Slots.Text = job.AvailableSlots?.ToString() ?? string.Empty;
            Unlimited.Pressed = job.AvailableSlots == null;
            Unlimited.Visible = HopJobPolicy.CanBeUnlimited(job.Id);
            Priority.Pressed = job.Priority;
            _loading = false;
        }
        PopulateJobs();
        UpdateButtons();
    }

    private void JobChanged()
    {
        if (_loading || _editing == null)
            return;
        _dirty = !TrySlots(out var slots) || slots != _editing.AvailableSlots || Priority.Pressed != _editing.Priority;
        UpdateButtons();
    }

    private bool TrySlots(out int? slots)
    {
        slots = null;
        if (_editing == null)
            return false;
        if (LiveJob?.SlotsLocked == true)
        {
            slots = _editing.AvailableSlots;
            return true;
        }
        if (Unlimited.Pressed && HopJobPolicy.CanBeUnlimited(_editing.Id))
            return true;
        if (!HopJobPolicy.CanBeUnlimited(_editing.Id) && _editing.AvailableSlots == null && Slots.Text.Length == 0)
            return true;
        if (!int.TryParse(Slots.Text, out var value) || !HopJobPolicy.ValidSlots(value))
            return false;
        slots = value;
        return true;
    }

    private void AdjustSlots(int delta)
    {
        if (int.TryParse(Slots.Text, out var slots))
            Slots.SetText(Math.Clamp(slots + delta, 0, LiveJob?.MaximumAvailable ?? 0).ToString(), invokeEvent: true);
        else if (Slots.Text.Length == 0)
            Slots.SetText("0", invokeEvent: true);
    }

    private void Save()
    {
        if (SaveJob.Disabled || _editing == null || !TrySlots(out var slots))
            return;
        Begin(HopConsoleOperation.SaveJob);
        _owner.SaveJob(_editing, slots, Priority.Pressed);
    }

    private void SelectRecord(uint? key)
    {
        _selectedRecord = key;
        RecordForm.Visible = false;
        DeleteConfirmation.Visible = false;
        UpdateRecordDetails();
        PopulateRecords();
        UpdateButtons();
    }

    private void UpdateRecordDetails()
    {
        var record = _state?.Records.FirstOrDefault(r => r.Key == _selectedRecord);
        RecordDetails.Visible = record != null && !RecordForm.Visible;
        RecordEmpty.Visible = record == null && !RecordForm.Visible;
        if (record == null)
            return;
        RecordName.Text = record.Name;
        RecordJob.Text = record.JobTitle;
        RecordNumber.Text = Loc.GetString("hop-console-record-number", ("id", record.Key));
    }

    private void ShowRecordForm(bool visible)
    {
        RecordForm.Visible = visible;
        DeleteConfirmation.Visible = false;
        UpdateRecordDetails();
        UpdateButtons();
    }

    private void Begin(HopConsoleOperation operation)
    {
        _pending = operation;
        SetStatus("hop-console-saving", false);
        UpdateButtons();
    }

    private void UpdateButtons()
    {
        var enabled = _pending == null && _state is { Available: true };
        var job = LiveJob;
        var valid = TrySlots(out var slots) && job != null &&
            HopJobPolicy.CanSetSlots(job.Id, slots, job.AvailableSlots, job.MaximumAvailable, job.SlotsLocked) &&
            (!job.PriorityLocked || Priority.Pressed == job.Priority);
        SaveJob.Disabled = !enabled || !_dirty || !valid;
        ResetJob.Disabled = !enabled || _editing == null;
        var editableSlots = enabled && job != null && !job.SlotsLocked &&
            !(Unlimited.Pressed && HopJobPolicy.CanBeUnlimited(job.Id));
        Slots.Editable = editableSlots;
        DecreaseSlots.Disabled = !editableSlots || slots == 0;
        IncreaseSlots.Disabled = !editableSlots || slots >= job?.MaximumAvailable;
        Unlimited.Disabled = !enabled || job?.SlotsLocked == true;
        Priority.Disabled = !enabled || job?.PriorityLocked == true;
        EventLock.Visible = job?.SlotsLocked == true;
        PriorityLock.Visible = job?.PriorityLocked == true;
        if (job != null)
        {
            Occupied.Text = job.OccupiedSlots.ToString();
            Maximum.Text = HopJobPolicy.CanBeUnlimited(job.Id) && job.ConfiguredSlots == null
                ? Loc.GetString("hop-console-unlimited-value")
                : job.MaximumAvailable.ToString();
        }
        AddRecord.Disabled = !enabled || _jobIds.Count == 0 || string.IsNullOrWhiteSpace(NewName.Text);
        NewName.Editable = NewTitle.Editable = enabled;
        NewJob.Disabled = !enabled || _jobIds.Count == 0;
        DeleteRecord.Disabled = ConfirmDelete.Disabled = !enabled || _selectedRecord == null;
        NewRecord.Disabled = !enabled;
        CancelNewRecord.Disabled = CancelDelete.Disabled = _pending != null;
    }

    private void SetStatus(string key, bool error)
    {
        Status.Text = Loc.GetString(key);
        Status.ToolTip = Status.Text;
        Status.FontColorOverride = Color.FromHex(error ? "#E6B86A" : "#9DAAB8");
    }

    private static bool Matches(string value, string query) =>
        value.Contains(query.Trim(), StringComparison.CurrentCultureIgnoreCase);

    private HopJobEntry? LiveJob => _state?.Jobs.FirstOrDefault(j => j.Id == _editing?.Id);

    private static (string, string, int?, bool, int?, int?, int, bool, bool) JobSnapshot(HopJobEntry job) =>
        (job.Id, job.Name, job.AvailableSlots, job.Priority, job.RoundStartSlots, job.ConfiguredSlots,
            job.OccupiedSlots, job.SlotsLocked, job.PriorityLocked);

    private static (uint, string, string, string) RecordSnapshot(HopRecordEntry record) =>
        (record.Key, record.Name, record.JobTitle, record.JobId);

    private static string FormatSlots(int? slots) =>
        slots?.ToString() ?? Loc.GetString("hop-console-unlimited-value");
}
