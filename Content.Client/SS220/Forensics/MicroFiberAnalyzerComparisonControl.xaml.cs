using Content.Shared.SS220.Forensics;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client.SS220.Forensics;

/// <summary>
/// Selects two archived samples and displays their matching glove and storage fibers.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class MicroFiberAnalyzerComparisonControl : BoxContainer
{
    private List<MicroFiberAnalyzerHistoryEntry> _history = [];

    /// <summary>
    /// The first archive record selected for comparison.
    /// </summary>
    public int? FirstSampleId { get; private set; }

    /// <summary>
    /// The second archive record selected for comparison.
    /// </summary>
    public int? SecondSampleId { get; private set; }

    /// <summary>
    /// Whether the selected records have a completed comparison.
    /// </summary>
    public bool HasResult { get; private set; }

    /// <summary>
    /// Raised when the comparison completes or its result is invalidated by a selection change.
    /// </summary>
    public event Action? OnResultChanged;

    /// <summary>
    /// Creates the comparison controls and initializes their status.
    /// </summary>
    public MicroFiberAnalyzerComparisonControl()
    {
        RobustXamlLoader.Load(this);
        ComparisonFirst.OnItemSelected += args => SelectSample(args.Id, true);
        ComparisonSecond.OnItemSelected += args => SelectSample(args.Id, false);
        ComparisonRun.OnPressed += _ => RunComparison();
        UpdateView();
    }

    /// <summary>
    /// Refreshes the archive choices while preserving valid selections and their comparison.
    /// </summary>
    public void UpdateHistory(List<MicroFiberAnalyzerHistoryEntry> history)
    {
        _history = history;
        var previousFirst = FirstSampleId;
        var previousSecond = SecondSampleId;
        ComparisonFirst.Clear();
        ComparisonSecond.Clear();
        ComparisonFirst.Disabled = history.Count == 0;
        ComparisonSecond.Disabled = history.Count == 0;

        for (var i = history.Count - 1; i >= 0; i--)
        {
            var sample = history[i];
            var sampleName = MicroFiberAnalyzerUi.GetSampleName(sample);
            ComparisonFirst.AddItem(sampleName, sample.Id);
            ComparisonSecond.AddItem(sampleName, sample.Id);
        }

        RestoreSelection();

        if (FirstSampleId != null)
            ComparisonFirst.SelectId(FirstSampleId.Value);

        if (SecondSampleId != null)
            ComparisonSecond.SelectId(SecondSampleId.Value);

        if (previousFirst != FirstSampleId || previousSecond != SecondSampleId)
            ClearComparison();

        UpdateView();
    }

    private void RestoreSelection()
    {
        if (_history.Count == 0)
        {
            FirstSampleId = null;
            SecondSampleId = null;
            return;
        }

        if (!HasSample(FirstSampleId))
            FirstSampleId = _history[^1].Id;

        if (HasSample(SecondSampleId))
            return;

        SecondSampleId = null;
        for (var i = _history.Count - 1; i >= 0; i--)
        {
            if (_history[i].Id == FirstSampleId)
                continue;

            SecondSampleId = _history[i].Id;
            break;
        }
    }

    private bool HasSample(int? id)
    {
        if (id == null)
            return false;

        return _history.Exists(sample => sample.Id == id.Value);
    }

    private void SelectSample(int id, bool first)
    {
        if (!HasSample(id))
            return;

        if (first)
        {
            FirstSampleId = id;
            ComparisonFirst.SelectId(id);
        }
        else
        {
            SecondSampleId = id;
            ComparisonSecond.SelectId(id);
        }

        ClearComparison();
        UpdateView();
    }

    private void ClearComparison()
    {
        var hadResult = HasResult;
        HasResult = false;
        ComparisonProfilesContainer.RemoveAllChildren();
        ComparisonStorageMicroFibersContainer.RemoveAllChildren();
        if (hadResult)
            OnResultChanged?.Invoke();
    }

    private void UpdateView()
    {
        ComparisonRun.Disabled = !CanCompareSelectedSamples();
        ComparisonResults.Visible = HasResult;
        ComparisonStatus.Visible = !HasResult;
        ComparisonStatus.SetMessage(FormattedMessage.FromUnformatted(Loc.GetString(GetStatusKey())));
    }

    private bool CanCompareSelectedSamples()
    {
        if (FirstSampleId == null)
            return false;

        if (SecondSampleId == null)
            return false;

        return FirstSampleId != SecondSampleId;
    }

    private string GetStatusKey()
    {
        if (FirstSampleId == null || SecondSampleId == null)
            return "micro-fiber-analyzer-interface-compare-not-enough";

        if (FirstSampleId == SecondSampleId)
            return "micro-fiber-analyzer-interface-compare-same-sample";

        return "micro-fiber-analyzer-interface-compare-instructions";
    }

    private void RunComparison()
    {
        if (!Visible)
            return;

        if (FirstSampleId == null)
            return;

        if (SecondSampleId == null)
            return;

        if (FirstSampleId == SecondSampleId)
            return;

        var first = _history.Find(sample => sample.Id == FirstSampleId.Value);
        var second = _history.Find(sample => sample.Id == SecondSampleId.Value);
        if (first == null || second == null)
            return;

        var gloveMatches = GloveMicroFiberComparison.FindGloveMatches(first.GloveMicroFibers, second.GloveMicroFibers);
        var storageMatches = GloveMicroFiberComparison.FindStorageMatches(first.StorageMicroFibers,
            second.StorageMicroFibers);
        DisplayResults(gloveMatches, storageMatches);
    }

    private void DisplayResults(List<GloveMicroFiberTrace> gloveMatches, List<StorageMicroFiberTrace> storageMatches)
    {
        ComparisonProfileCount.Text = Loc.GetString("micro-fiber-analyzer-interface-compare-profile-count",
            ("count", gloveMatches.Count));
        ComparisonStorageMicroFiberCount.Text = Loc.GetString(
            "micro-fiber-analyzer-interface-compare-storage-micro-fiber-count",
            ("count", storageMatches.Count));
        ComparisonProfilesContainer.ShowGloveSamples(gloveMatches,
            Loc.GetString("micro-fiber-analyzer-interface-compare-no-profiles"));
        ComparisonStorageMicroFibersContainer.ShowStorageSamples(storageMatches,
            Loc.GetString("micro-fiber-analyzer-interface-compare-no-storage-micro-fibers"));
        HasResult = true;
        UpdateView();
        OnResultChanged?.Invoke();
    }
}
