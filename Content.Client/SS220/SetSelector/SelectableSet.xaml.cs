using Content.Shared.SS220.SetSelector;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.SS220.SetSelector;

[GenerateTypedNameReferences]
public sealed partial class SelectableSet : BoxContainer
{
    public SelectableSet(SelectableSetPrototype set, SpriteSystem sprite)
    {
        RobustXamlLoader.Load(this);

        Icon.Texture = sprite.Frame0(set.Sprite);
        SetName.Text = Loc.GetString(set.Name);
        SetDescription.SetMessage(Loc.GetString(set.Description));
    }

    public void SetSelected(bool selected, bool disabled)
    {
        SetButton.Pressed = selected;
        SetButton.Disabled = disabled;
        SetButton.Text = Loc.GetString(selected ? "set-selector-button-deselect" : "set-selector-button-select");
    }
}
