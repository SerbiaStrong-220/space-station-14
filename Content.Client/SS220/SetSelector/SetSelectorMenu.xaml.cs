using Content.Client.UserInterface.Controls;
using Content.Shared.SS220.SetSelector;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client.SS220.SetSelector;

[GenerateTypedNameReferences]
public sealed partial class SetSelectorMenu : FancyWindow
{
    [Dependency] private IEntityManager _entMan = default!;
    [Dependency] private IPrototypeManager _proto = default!;

    private readonly SpriteSystem _sprite;

    public event Action? OnApprove;
    public event Action<int>? OnSetChange;

    public SetSelectorMenu()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _sprite = _entMan.System<SpriteSystem>();

        ApproveButton.OnPressed += _ => OnApprove?.Invoke();
    }

    public void UpdateState(SetSelectorBoundUserInterfaceState state)
    {
        SetsGrid.RemoveAllChildren();
        for (var i = 0; i < state.Sets.Count; i++)
        {
            var index = i;
            var child = new SelectableSet(_proto.Index(state.Sets[i]), state.Selected.Contains(i), _sprite);
            child.SetButton.OnButtonDown += _ => OnSetChange?.Invoke(index);
            SetsGrid.AddChild(child);
        }

        Title = Loc.GetString(state.ToolName);
        Description.Text = Loc.GetString(state.ToolDesc, ("maxCount", state.MaxSelectedSets));
        SelectedSets.Text = Loc.GetString("set-selector-window-selected", ("selectedCount", state.Selected.Count), ("maxCount", state.MaxSelectedSets));
        ApproveButton.Disabled = state.Selected.Count != state.MaxSelectedSets;
    }
}
