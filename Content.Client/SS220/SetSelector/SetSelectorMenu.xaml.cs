using System.Linq;
using Content.Client.Stylesheets;
using Content.Client.UserInterface.Controls;
using Content.Shared.SS220.SetSelector;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client.SS220.SetSelector;

[GenerateTypedNameReferences]
public sealed partial class SetSelectorMenu : FancyWindow
{
    [Dependency] private IEntityManager _entMan = default!;
    [Dependency] private IPrototypeManager _proto = default!;

    private readonly SpriteSystem _sprite;
    private readonly List<SelectableSet> _setControls = new();
    private List<ProtoId<SelectableSetPrototype>> _setIds = new();

    public event Action? OnApprove;
    public event Action<int>? OnSetChange;

    public SetSelectorMenu()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _sprite = _entMan.System<SpriteSystem>();

        ApproveButton.OnPressed += _ => OnApprove?.Invoke();
    }

    public void Update(
        IReadOnlyList<ProtoId<SelectableSetPrototype>> sets,
        IReadOnlyList<int> selected,
        int maxSelected,
        LocId toolName,
        LocId toolDesc)
    {
        if (!sets.SequenceEqual(_setIds))
            BuildSets(sets);

        var locked = maxSelected > 1 && selected.Count >= maxSelected;
        for (var i = 0; i < _setControls.Count; i++)
        {
            var isSelected = selected.Contains(i);
            _setControls[i].SetSelected(isSelected, !isSelected && locked);
        }

        Title = Loc.GetString(toolName);
        Heading.Text = Loc.GetString("set-selector-window-heading", ("maxCount", maxSelected));
        Description.SetMessage(Loc.GetString(toolDesc, ("maxCount", maxSelected)), Color.DarkGray);
        SelectedSets.Text = Loc.GetString("set-selector-window-selected", ("selectedCount", selected.Count), ("maxCount", maxSelected));
        ApproveButton.Disabled = selected.Count != maxSelected;
    }

    private void BuildSets(IReadOnlyList<ProtoId<SelectableSetPrototype>> sets)
    {
        SetsContainer.RemoveAllChildren();
        _setControls.Clear();
        _setIds = new(sets);

        for (var i = 0; i < sets.Count; i++)
        {
            if (i > 0)
                SetsContainer.AddChild(new PanelContainer { StyleClasses = { StyleClass.LowDivider } });

            var index = i;
            var control = new SelectableSet(_proto.Index(sets[i]), _sprite);
            control.SetButton.OnPressed += _ => OnSetChange?.Invoke(index);
            SetsContainer.AddChild(control);
            _setControls.Add(control);
        }
    }
}
