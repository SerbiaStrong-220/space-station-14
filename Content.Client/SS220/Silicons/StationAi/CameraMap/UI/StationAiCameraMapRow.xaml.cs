using Content.Shared.SS220.Silicons.StationAi.CameraMap;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.SS220.Silicons.StationAi.CameraMap.UI;

[GenerateTypedNameReferences]
public sealed partial class StationAiCameraMapRow : ContainerButton
{
    private static readonly Color ActiveColor = Color.LimeGreen;
    private static readonly Color InactiveColor = Color.DarkRed;

    public readonly StationAiCameraMapTarget Camera;

    public event Action<NetEntity>? OnFavoriteToggled;

    public StationAiCameraMapRow(StationAiCameraMapTarget camera, bool favorite)
    {
        RobustXamlLoader.Load(this);

        Camera = camera;
        Disabled = !camera.Active;
        ToolTip = Loc.GetString(camera.Active ? "station-ai-camera-map-row-active" : "station-ai-camera-map-row-inactive",
            ("name", camera.Name));
        StatusDot.Modulate = camera.Active ? ActiveColor : InactiveColor;
        CameraName.Text = camera.Name;
        PinButton.Text = favorite ? "★" : "☆";
        PinButton.ToolTip = Loc.GetString(favorite ? "station-ai-camera-map-unpin" : "station-ai-camera-map-pin");
        PinButton.OnPressed += _ => OnFavoriteToggled?.Invoke(camera.Entity);
    }
}
