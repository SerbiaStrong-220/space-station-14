using System.Linq;
using Content.Client.Pinpointer.UI;
using Content.Client.UserInterface.Controls;
using Content.Shared.SS220.Silicons.StationAi.CameraMap;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Map;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client.SS220.Silicons.StationAi.CameraMap.UI;

[GenerateTypedNameReferences]
public sealed partial class StationAiCameraMapWindow : FancyWindow
{
    [Dependency] private readonly IEntityManager _entMan = default!;
    [Dependency] private readonly IGameTiming _timing = default!;

    // Cooldown bar fills; dimmed so the white text stays readable.
    private static readonly Color ReadyColor = Color.FromHex("#386E5C");
    private static readonly Color CooldownColor = Color.FromHex("#8C6424");
    private static readonly Color FailureColor = Color.FromHex("#822C2C");
    private static readonly TimeSpan FailureDuration = TimeSpan.FromSeconds(2.5);
    private static readonly ResPath BlipPath = new("/Textures/Interface/NavMap/beveled_circle.png");

    private readonly Texture _blip;
    private readonly StyleBoxFlat _barFill = new(ReadyColor);
    private EntityUid _grid;
    private List<StationAiCameraMapTarget> _mapTargets = new();
    private List<StationAiCameraMapTarget> _cameras = new();
    private IReadOnlySet<NetEntity> _favorites = new HashSet<NetEntity>();
    private TimeSpan _nextJump;
    private TimeSpan _cooldown;
    private TimeSpan _failureUntil;
    private string? _failure;

    public event Action<NetEntity>? OnJump;
    public event Action<NetEntity>? OnFavoriteToggled;

    public StationAiCameraMapWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _blip = _entMan.System<SpriteSystem>().Frame0(new SpriteSpecifier.Texture(BlipPath));
        CooldownBar.ForegroundStyleBoxOverride = _barFill;
        foreach (var filter in Enum.GetValues<StatusFilterMode>())
        {
            StatusFilter.AddItem(Loc.GetString($"station-ai-camera-map-status-{filter.ToString().ToLowerInvariant()}"),
                (int) filter);
        }

        StatusFilter.OnItemSelected += args =>
        {
            StatusFilter.SelectId(args.Id);
            ApplyFilter();
        };
        SearchLineEdit.OnTextChanged += _ => ApplyFilter();
        NavMap.TrackedEntitySelectedAction += target =>
        {
            if (target == null)
                return;

            if (Tabs.CurrentTab == CrewTab)
                OnCrewJump?.Invoke(target.Value);
            else
                OnJump?.Invoke(target.Value);
        };
        Tabs.SetTabTitle(CamerasTab, Loc.GetString("station-ai-camera-map-tab-cameras"));
        Tabs.SetTabTitle(CrewTab, Loc.GetString("station-ai-camera-map-tab-crew"));
        Tabs.OnTabChanged += _ => UpdateBlips();
        InitializeCrew();
        RebuildRows();
    }

    public void UpdateState(EntityUid grid, StationAiCameraMapState state)
    {
        if (NavMap.MapUid != grid)
        {
            NavMap.MapUid = grid;
            NavMap.ForceNavMapUpdate();
        }

        _grid = grid;
        _mapTargets = state.Targets;
        UpdateCrew(state);
        UpdateBlips();

        // Sorted the same way every time, so an unchanged list does not rebuild the rows.
        var cameras = state.Targets.Where(t => t.IsCamera)
            .OrderBy(t => t.Name, StringComparer.CurrentCultureIgnoreCase)
            .ToList();
        if (_cameras.SequenceEqual(cameras))
            return;

        _cameras = cameras;
        RebuildRows();
    }

    public void SetFavorites(IReadOnlySet<NetEntity> favorites)
    {
        _favorites = favorites;
        RebuildRows();
    }

    public void SetCooldown(TimeSpan nextJump, TimeSpan cooldown)
    {
        _nextJump = nextJump;
        _cooldown = cooldown;
    }

    public void ShowFailure(StationAiCameraMapFailure failure)
    {
        _failure = Loc.GetString(failure switch
        {
            StationAiCameraMapFailure.CameraInactive => "station-ai-camera-map-camera-inactive",
            StationAiCameraMapFailure.NoCoordinates => "station-ai-camera-map-no-coordinates",
            StationAiCameraMapFailure.OutOfView => "station-ai-camera-map-out-of-view",
            _ => "station-ai-camera-map-no-camera-nearby",
        });
        _failureUntil = _timing.CurTime + FailureDuration;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        var remaining = _nextJump - _timing.CurTime;
        string text;
        if (_failure != null && _timing.CurTime < _failureUntil)
        {
            CooldownBar.Value = 1;
            _barFill.BackgroundColor = FailureColor;
            text = _failure;
        }
        else if (remaining > TimeSpan.Zero && _cooldown > TimeSpan.Zero)
        {
            CooldownBar.Value = 1 - (float) (remaining / _cooldown);
            _barFill.BackgroundColor = CooldownColor;
            text = Loc.GetString("station-ai-camera-map-cooldown", ("seconds", remaining.TotalSeconds.ToString("0.0")));
        }
        else
        {
            CooldownBar.Value = 1;
            _barFill.BackgroundColor = ReadyColor;
            text = Loc.GetString("station-ai-camera-map-ready");
        }

        if (CooldownLabel.Text != text)
            CooldownLabel.Text = text;
    }

    /// <summary>
    ///     The map shows only what the open tab can jump to.
    /// </summary>
    private void UpdateBlips()
    {
        NavMap.TrackedEntities.Clear();
        NavMap.Names.Clear();
        if (Tabs.CurrentTab == CrewTab)
        {
            AddCrewBlips();
            return;
        }

        foreach (var target in _mapTargets)
        {
            var color = target.IsCamera ? Color.Cyan : Color.Orange;
            var name = target.Name;
            if (!target.Active)
            {
                color = color.WithAlpha(0.35f) * Color.DimGray;
                name = Loc.GetString(target.IsCamera ? "station-ai-camera-map-blip-inactive" : "station-ai-camera-map-blip-uncovered",
                    ("name", target.Name));
            }

            NavMap.TrackedEntities[target.Entity] = new NavMapBlip(new EntityCoordinates(_grid, target.Position), _blip, color, false);
            NavMap.Names[target.Entity] = name;
        }
    }

    private void RebuildRows()
    {
        FavoritesList.DisposeAllChildren();
        CamerasList.DisposeAllChildren();
        foreach (var camera in _cameras)
        {
            var favorite = _favorites.Contains(camera.Entity);
            var row = new StationAiCameraMapRow(camera, favorite);
            row.OnPressed += _ => OnJump?.Invoke(camera.Entity);
            row.OnFavoriteToggled += entity => OnFavoriteToggled?.Invoke(entity);
            (favorite ? FavoritesList : CamerasList).AddChild(row);
        }

        ApplyFilter();
    }

    private void ApplyFilter()
    {
        var search = SearchLineEdit.Text.Trim();
        var mode = (StatusFilterMode) StatusFilter.SelectedId;
        var favoritesShown = FilterList(FavoritesList, search, mode, out var favoritesActive);
        var othersShown = FilterList(CamerasList, search, mode, out var othersActive);

        FavoritesHeader.Visible = favoritesShown > 0;
        FavoritesCount.Text = Loc.GetString("station-ai-camera-map-active-count", ("count", favoritesActive));
        CamerasHeader.Visible = othersShown > 0;
        CamerasTitle.Text = Loc.GetString(favoritesShown > 0 ? "station-ai-camera-map-other" : "station-ai-camera-map-all");
        CamerasCount.Text = Loc.GetString("station-ai-camera-map-active-count", ("count", othersActive));
        EmptyLabel.Visible = favoritesShown + othersShown == 0;
    }

    private static int FilterList(BoxContainer list, string search, StatusFilterMode mode, out int active)
    {
        var shown = 0;
        active = 0;
        foreach (var child in list.Children)
        {
            if (child is not StationAiCameraMapRow row)
                continue;

            var camera = row.Camera;
            row.Visible = camera.Name.Contains(search, StringComparison.CurrentCultureIgnoreCase)
                && (mode == StatusFilterMode.All || camera.Active == (mode == StatusFilterMode.Active));
            if (!row.Visible)
                continue;

            shown++;
            if (camera.Active)
                active++;
        }

        return shown;
    }

    private const int CamerasTab = 0;
    private const int CrewTab = 1;

    private enum StatusFilterMode
    {
        All,
        Active,
        Inactive,
    }
}
