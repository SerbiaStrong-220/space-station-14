using System.Numerics;
using Content.Shared.SS220.Silicons.StationAi.CameraMap;
using Content.Shared.StatusIcon;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;

namespace Content.Client.SS220.Silicons.StationAi.CameraMap.UI;

[GenerateTypedNameReferences]
public sealed partial class StationAiCrewRow : ContainerButton
{
    private static readonly ResPath HealthRsi = new("Interface/Alerts/human_crew_monitoring.rsi");

    public readonly StationAiCameraMapCrew Crew;

    public StationAiCrewRow(StationAiCameraMapCrew crew, SpriteSystem sprites, IPrototypeManager prototypes)
    {
        RobustXamlLoader.Load(this);

        Crew = crew;
        Disabled = !crew.Located;
        ToolTip = Loc.GetString(crew.Located ? "station-ai-camera-map-crew-row" : "station-ai-camera-map-crew-row-no-coordinates",
            ("name", crew.Name), ("job", crew.Job));
        LocatedDot.Modulate = crew.Located ? Color.LimeGreen : Color.DarkRed;
        HealthIcon.SetFromSpriteSpecifier(new SpriteSpecifier.Rsi(HealthRsi, HealthState(crew)));
        HealthIcon.DisplayRect.TextureScale = new Vector2(2f, 2f);
        CrewName.Text = crew.Name;
        JobName.Text = crew.Job;
        if (prototypes.TryIndex<JobIconPrototype>(crew.JobIcon, out var icon))
            JobIcon.Texture = sprites.Frame0(icon.Icon);
    }

    /// <summary>
    ///     Health label state, as the crew monitoring console picks it.
    /// </summary>
    private static string HealthState(StationAiCameraMapCrew crew)
    {
        if (!crew.Alive)
            return "dead";

        return crew.HealthLevel switch
        {
            null => "alive",
            >= 5 => "critical",
            var level => "health" + level,
        };
    }

    /// <summary>
    ///     Map marker colour, as the crew monitoring console picks it.
    /// </summary>
    public static Color DotColor(StationAiCameraMapCrew crew)
    {
        if (!crew.Alive)
            return Color.Violet;

        return crew.HealthLevel switch
        {
            null => Color.LightGray,
            0 or 1 => Color.LimeGreen,
            2 => Color.Gold,
            3 or 4 => Color.Crimson,
            _ => Color.Red,
        };
    }
}
