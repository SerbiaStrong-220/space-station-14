using Content.Client.UserInterface.Controls;
using Content.Shared.SS220.Silicons.Laws;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.SS220.Silicons.Laws;

[GenerateTypedNameReferences]
public sealed partial class LawUploadWindow : FancyWindow
{
    public event Action<LawUploadTarget, int>? OnApply;
    public event Action<string>? OnEject;
    private int _revision;

    public LawUploadWindow()
    {
        RobustXamlLoader.Load(this);
        EjectCard.OnPressed += _ => OnEject?.Invoke(LawUploadConsoleComponent.CardSlot);
        EjectBoard.OnPressed += _ => OnEject?.Invoke(LawUploadConsoleComponent.BoardSlot);
        ApplyAi.OnPressed += _ => Apply(LawUploadTarget.Ai);
        ApplyBorgs.OnPressed += _ => Apply(LawUploadTarget.Borgs);
        ApplyAll.OnPressed += _ => Apply(LawUploadTarget.All);
    }

    private void Apply(LawUploadTarget target)
    {
        ApplyAi.Disabled = ApplyBorgs.Disabled = ApplyAll.Disabled = true;
        OnApply?.Invoke(target, _revision);
    }

    public void UpdateState(LawUploadState state)
    {
        _revision = state.Revision;
        Status.SetMessage(Loc.GetString(state.Status));
        AiTitle.SetMessage(Loc.GetString("law-upload-ai-name", ("name", state.AiName)));
        BorgTitle.SetMessage(Loc.GetString("law-upload-borg-name", ("name", state.BorgName)));
        AiLaws.SetMessage(string.Join("\n", state.AiLaws));
        BorgLaws.SetMessage(string.Join("\n", state.BorgLaws));
        BoardTitle.SetMessage(state.HasBoard ? state.BoardName : Loc.GetString("law-upload-insert-board"));
        BoardLaws.SetMessage(string.Join("\n", state.BoardLaws));
        EjectCard.Disabled = !state.HasCard;
        EjectBoard.Disabled = !state.HasBoard;
        ApplyAi.Disabled = ApplyBorgs.Disabled = ApplyAll.Disabled = !state.CanApply;
    }
}
