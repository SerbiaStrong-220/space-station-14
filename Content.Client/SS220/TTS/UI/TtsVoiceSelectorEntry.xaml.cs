using Content.Shared.SS220.TTS.Prototypes;
using Robust.Client.AutoGenerated;
using Robust.Client.Player;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Player;
using Robust.Shared.Utility;

namespace Content.Client.SS220.TTS.UI;

[GenerateTypedNameReferences]
public sealed partial class TtsVoiceSelectorEntry : PanelContainer
{
    [Dependency] private IEntityManager _entity = default!;
    [Dependency] private IPlayerManager _player = default!;

    private readonly TtsSystem _tts;

    public event Action<TtsVoicePrototype>? OnVoiceSelected;

    public TtsVoicePrototype Voice { get; private set; }

    public bool Locked { get; private set; } = false;

    private readonly Tooltip _tooltip = new();
    private readonly Tooltip _lockedOverlayTooltip = new();

    private const float DimmedContentAlpha = 0.05f;

    public TtsVoiceSelectorEntry(TtsVoicePrototype voice)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _tts = _entity.System<TtsSystem>();

        Voice = voice;

        SelectButton.OnPressed += _ =>
        {
            if (Locked)
                return;

            OnVoiceSelected?.Invoke(Voice);
        };

        PlayButton.OnPressed += _ =>
        {
            if (Locked)
                return;

            _tts.RequestVoiceTest(Voice);
        };

        Refresh();
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();

        _tts.OnSessionVoiceTestCooldownUpdated += OnVoiceTestCooldownUpdated;
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();

        _tts.OnSessionVoiceTestCooldownUpdated -= OnVoiceTestCooldownUpdated;
    }

    private void OnVoiceTestCooldownUpdated(ICommonSession session)
    {
        RefreshPlayButton();
    }

    public void Refresh()
    {
        NameLabel.Text = Voice.LocalizedName;

        var descriptionMsg = FormattedMessage.FromMarkupPermissive(Voice.LocalizedDescription);
        if (!descriptionMsg.IsEmpty)
        {
            _tooltip.SetMessage(descriptionMsg);
            TooltipSupplier = _ => _tooltip;
        }
        else
            TooltipSupplier = null;
    }

    public void SetVoice(TtsVoicePrototype voice)
    {
        Voice = voice;
        Refresh();
    }

    public void Lock(FormattedMessage? reason = null)
    {
        LockedOverlay.Visible = true;

        if (reason != null && !reason.IsEmpty)
        {
            _lockedOverlayTooltip.SetMessage(reason);
            LockedOverlay.TooltipSupplier = _ => _lockedOverlayTooltip;
        }
        else
            LockedOverlay.TooltipSupplier = null;

        Locked = true;

        ContentPanel.Modulate = Color.White.WithAlpha(DimmedContentAlpha);
    }

    public void Unlock()
    {
        LockedOverlay.Visible = false;
        Locked = false;

        ContentPanel.Modulate = Color.White;
    }

    private void RefreshPlayButton()
    {
        if (_player.LocalSession is not { } session)
            return;

        var voiceTestCooldowned = _tts.IsVoiceTestCooldowned(session);
        PlayButton.Disabled = voiceTestCooldowned;
        PlayButton.ToolTip = voiceTestCooldowned ? Loc.GetString("ui-tts-voice-test-cooldowned-tooltip") : null;
    }
}
