using Content.Shared.SS220.TTS;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.SS220.TTS.UI;

[GenerateTypedNameReferences]
public sealed partial class TtsVoiceSelectorEntry : BoxContainer
{
    private readonly TtsSystem _tts;

    public event Action<TtsVoicePrototype>? OnVoiceSelected;

    public TtsVoicePrototype Voice { get; private set; }

    public TtsVoiceSelectorEntry(TtsVoicePrototype voice)
    {
        RobustXamlLoader.Load(this);

        _tts = IoCManager.Resolve<IEntitySystemManager>().GetEntitySystem<TtsSystem>();

        Voice = voice;

        SelectButton.OnPressed += _ => OnVoiceSelected?.Invoke(Voice);
        PlayButton.OnPressed += _ => _tts.RequestVoiceTest(Voice);

        Refresh();
    }

    public void Refresh()
    {
        NameLabel.Text = Voice.Name;
    }

    public void SetVoice(TtsVoicePrototype voice)
    {
        Voice = voice;
        Refresh();
    }
}
