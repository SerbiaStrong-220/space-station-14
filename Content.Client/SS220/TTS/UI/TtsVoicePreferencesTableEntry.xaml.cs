using Content.Shared.SS220.TTS.Prototypes;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.Player;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Player;
using Robust.Shared.Utility;

namespace Content.Client.SS220.TTS.UI;

[GenerateTypedNameReferences]
public sealed partial class TtsVoicePreferencesTableEntry : BoxContainer
{
    [Dependency] private IEntityManager _entity = default!;
    [Dependency] private IPlayerManager _player = default!;

    public Action? OnExitedTree;

    private readonly TtsSystem _tts = default!;

    public readonly TtsVoicePrototype Prototype;

    private Tooltip? _tooltip;

    public TtsVoicePreferencesTableEntry(TtsVoicePrototype proto)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _tts = _entity.System<TtsSystem>();

        Background.PanelOverride = new StyleBoxFlat()
        {
            BackgroundColor = TtsVoicePreferencesTable.CellBackgroundColor
        };
        ProviderNameLabel.SetWidth = TtsVoicePreferencesTable.ProviderColumnWidth;

        Prototype = proto;

        VoicePlayButton.OnPressed += _ => _tts.RequestVoiceTest(Prototype);

        Refresh();
    }


    protected override void EnteredTree()
    {
        base.EnteredTree();

        _tts.OnSessionVoiceTestCooldownUpdated += OnVoiceTestCooldownUpdated;
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();

        _tts.OnSessionVoiceTestCooldownUpdated -= OnVoiceTestCooldownUpdated;
        OnExitedTree?.Invoke();
    }

    private void OnVoiceTestCooldownUpdated(ICommonSession session)
    {
        RefreshPlayButton();
    }

    public void Refresh()
    {
        ProviderNameLabel.Text = Prototype.Provider.ToString();
        VoiceNameLabel.Text = Prototype.LocalizedName;

        RefreshPlayButton();
    }

    public void SetHighlightColor(Color? color)
    {
        if (color == null)
        {
            HighlightOverlay.Visible = false;
            return;
        }

        HighlightOverlay.Visible = true;

        if (HighlightOverlay.PanelOverride is not StyleBoxFlat styleBoxFlat)
        {
            styleBoxFlat = new StyleBoxFlat();
            HighlightOverlay.PanelOverride = styleBoxFlat;
        }

        styleBoxFlat.BackgroundColor = color.Value;
    }

    public void SetTooltipMsg(FormattedMessage? msg)
    {
        if (msg == null)
        {
            TooltipSupplier = null;
            return;
        }

        _tooltip ??= new();
        _tooltip.SetMessage(msg);
        TooltipSupplier = _ => _tooltip;
    }

    private void RefreshPlayButton()
    {
        if (_player.LocalSession is not { } session)
            return;

        var voiceTestCooldowned = _tts.IsVoiceTestCooldowned(session);
        VoicePlayButton.Disabled = voiceTestCooldowned;
        VoicePlayButton.ToolTip = voiceTestCooldowned ? Loc.GetString("ui-tts-voice-test-cooldowned-tooltip") : null;
    }
}
