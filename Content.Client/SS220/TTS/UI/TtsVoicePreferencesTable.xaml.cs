using Content.Client.SS220.UserInterface;
using Content.Shared.SS220.TTS;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.Input;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Input;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client.SS220.TTS.UI;

[GenerateTypedNameReferences]
public sealed partial class TtsVoicePreferencesTable : BoxContainer
{
    [Dependency] private IUserInterfaceManager _ui = default!;
    [Dependency] private IInputManager _input = default!;
    [Dependency] private IPrototypeManager _proto = default!;

    private readonly TtsSystem _tts;

    public event Action? OnPreferencesChanged;

    public static readonly Color CellBackgroundColor = Color.FromHex("#2F2F3B");
    public const float ProviderColumnWidth = 250f;

    public TtsVoicePreferences VoicePreferences { get; private set; }

    private int? _draggedEntryStartPos;
    private TtsVoicePreferencesTableEntry? _draggingEntry;

    private TtsProviderVoiceSelectorWindow? _selectorWindow;
    private TtsVoicePreferencesTableEntry? _editingEntry;

    private readonly Dictionary<TtsProvider, TtsVoicePreferencesTableEntry> _entriesDict = [];

    private static readonly Color EntryLowWarningColor = Color.Yellow.WithAlpha(0.2f);
    private static readonly Color EntryHighWarningColor = Color.Red.WithAlpha(0.2f);
    private static readonly Color DraggingEntryColor = Color.FromHex("#969696B3");

    public TtsVoiceRequirementCheckData? RequirementsCheckData
    {
        get => _requirementsCheckData;
        set
        {
            if (_requirementsCheckData == value)
                return;

            _requirementsCheckData = value;
            _selectorWindow?.RequirementsCheckData = value;

            foreach (var entry in _entriesDict.Values)
                RefreshEntryState(entry);
        }
    }
    private TtsVoiceRequirementCheckData? _requirementsCheckData;

    public TtsVoicePreferencesTable() : this(null) { }

    public TtsVoicePreferencesTable(TtsVoicePreferences? preferences = null)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _tts = IoCManager.Resolve<IEntitySystemManager>().GetEntitySystem<TtsSystem>();

        ProviderHeaderBackground.PanelOverride = new StyleBoxFlat()
        {
            BackgroundColor = CellBackgroundColor
        };
        ProviderHeaderLabel.SetWidth = ProviderColumnWidth;

        preferences ??= [];

        // fill not setted providers
        preferences.SoftMergeWith(SharedTtsSystem.DefaultVoicePreferences);

        VoicePreferences = preferences;

        OnKeyBindUp += args =>
        {
            if (args.Function != EngineKeyFunctions.UIClick)
                return;

            StopDragEntry();
        };

        _tts.OnTtsProviderStateChanged += OnProviderStateChanged;

        Refresh();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        if (_draggingEntry != null && _draggingEntry.Parent != null)
        {
            const float swapThreshold = 5f;

            var entryBox = _draggingEntry.SizeBox;
            var entryMousePos = _ui.MousePositionScaled.Position - _draggingEntry.GlobalPosition;

            var indexDelta = 0;
            if (entryMousePos.Y < entryBox.Top - swapThreshold)
                indexDelta = -1;
            else if (entryMousePos.Y > entryBox.Bottom + swapThreshold)
                indexDelta = 1;

            if (indexDelta == 0)
                return;

            var oldIndex = _draggingEntry.GetPositionInParent();
            var newIndex = Math.Clamp(oldIndex + indexDelta, 0, EntriesContainer.ChildCount - 1);

            if (newIndex == oldIndex)
                return;

            var childOnNewIndex = EntriesContainer.GetChild(newIndex);

            _draggingEntry.SetPositionInParent(newIndex);
            childOnNewIndex.SetPositionInParent(oldIndex);

            if (newIndex == 0)
            {
                _draggingEntry.BeforeContentDivider.Visible = false;

                if (childOnNewIndex is TtsVoicePreferencesTableEntry entry)
                    entry.BeforeContentDivider.Visible = true;
            }

            EntriesContainer.InvalidateMeasure();
        }
    }

    protected override void MouseExited()
    {
        base.MouseExited();

        var hoveredControl = _ui.MouseGetControl(_input.MouseScreenPosition);
        if (hoveredControl != null && hoveredControl.IsChildOf(this, recurcive: true))
            return;

        StopDragEntry();
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();

        CloseSelecotorWindow();
        _tts.OnTtsProviderStateChanged -= OnProviderStateChanged;
    }

    private void OnProviderStateChanged(TtsProvider provider, bool enabled)
    {
        if (!_entriesDict.TryGetValue(provider, out var entry))
            return;

        RefreshEntryState(entry);
    }

    public void Refresh()
    {
        EntriesContainer.RemoveAllChildren();
        _entriesDict.Clear();

        var first = true;
        foreach (var (provider, protoId) in VoicePreferences)
        {
            if (!_proto.TryIndex(protoId, out var proto))
            {
                DebugTools.Assert($"Failed to index voice prototype with id {protoId}");
                continue;
            }

            DebugTools.Assert(provider == proto.Provider, $"Prototype {protoId} does not use provider {provider.ToString()}");

            var entry = new TtsVoicePreferencesTableEntry(proto);
            entry.OnKeyBindDown += args =>
            {
                if (args.Function != EngineKeyFunctions.UIClick)
                    return;

                StartDragEntry(entry);
            };

            entry.VoiceSelectorButton.OnPressed += _ => OpenSelectorWindow(provider);
            entry.OnExitedTree += () =>
            {
                if (entry != _editingEntry)
                    return;

                CloseSelecotorWindow();
            };

            if (first)
                first = false;
            else
                entry.BeforeContentDivider.Visible = true;

            RefreshEntryState(entry);

            EntriesContainer.AddChild(entry);
            _entriesDict.Add(provider, entry);
        }
    }

    public void SetPreferences(TtsVoicePreferences pref, bool silent = false)
    {
        // fill not setted providers
        pref.SoftMergeWith(SharedTtsSystem.DefaultVoicePreferences);

        VoicePreferences = pref;
        Refresh();

        if (!silent)
            OnPreferencesChanged?.Invoke();
    }

    private void RefreshEntryState(TtsVoicePreferencesTableEntry entry)
    {
        Color? highlightColor = null;
        FormattedMessage? tooltipMsg = null;

        if (entry == _draggingEntry)
            highlightColor = DraggingEntryColor;
        else if (_requirementsCheckData is { } checkData && !_tts.IsPassVoiceRequirements(entry.Prototype, checkData, out var reason))
        {
            highlightColor = EntryHighWarningColor;
            tooltipMsg = FormattedMessage.FromMarkupPermissive(Loc.GetString("ui-tts-voice-preferences-tab-voice-not-allowed", ("reason", reason.ToMarkup())));
        }
        else if (!_tts.IsProviderEnabled(entry.Prototype.Provider))
        {
            highlightColor = EntryLowWarningColor;
            tooltipMsg = FormattedMessage.FromMarkupPermissive(Loc.GetString("ui-tts-voice-preferences-tab-provider-disabled", ("provider", entry.Prototype.Provider.ToString())));
        }

        entry.SetHighlightColor(highlightColor);
        entry.SetTooltipMsg(tooltipMsg);
    }

    private void OpenSelectorWindow(TtsProvider provider)
    {
        if (_selectorWindow != null)
            CloseSelecotorWindow();

        if (!_entriesDict.TryGetValue(provider, out var entry))
            return;

        entry.VoiceSelectorButton.Pressed = true;

        var window = new TtsProviderVoiceSelectorWindow(provider, _requirementsCheckData);
        window.OnClose += CloseSelecotorWindow;
        window.OnVoiceSelected += voice =>
        {
            VoicePreferences[provider] = voice;
            CloseSelecotorWindow();
            Refresh();

            OnPreferencesChanged?.Invoke();
        };

        window.OpenCentered();
        _selectorWindow = window;
        _editingEntry = entry;
    }

    private void CloseSelecotorWindow()
    {
        if (_selectorWindow == null)
            return;

        _selectorWindow.Close();
        _selectorWindow = null;

        _editingEntry?.VoiceSelectorButton.Pressed = false;
        _editingEntry = null;
    }

    private void StartDragEntry(TtsVoicePreferencesTableEntry entry)
    {
        StopDragEntry();

        if (entry.Parent == null)
            return;

        DebugTools.Assert(_draggingEntry == null);

        _draggingEntry = entry;
        _draggedEntryStartPos = _draggingEntry.GetPositionInParent();

        RefreshEntryState(entry);
    }

    private void StopDragEntry()
    {
        if (_draggingEntry == null)
            return;

        var entry = _draggingEntry;

        var newPos = entry.GetPositionInParent();
        if (newPos != _draggedEntryStartPos)
        {
            VoicePreferences.Remove(entry.Prototype.Provider);
            VoicePreferences.Insert(newPos, entry.Prototype.Provider, entry.Prototype);
            Refresh();

            OnPreferencesChanged?.Invoke();
        }

        _draggingEntry = null;
        _draggedEntryStartPos = null;

        RefreshEntryState(entry);
    }
}
