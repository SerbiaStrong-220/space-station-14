using Content.Shared.SS220.TTS;
using Content.Shared.SS220.TTS.Prototypes;
using Content.Shared.SS220.TTS.Requirements;
using Content.Shared.SS220.TTS.Systems;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;
using System.Linq;

namespace Content.Client.SS220.TTS.UI;

[GenerateTypedNameReferences]
public sealed partial class TtsProviderVoiceSelectorWindow : DefaultWindow
{
    private readonly TtsSystem _tts;

    public const float BetweenCategoriesMargin = 30f;

    public event Action<TtsVoicePrototype>? OnVoiceSelected;

    private const int AllCategoriesOptionId = 0;

    private readonly Dictionary<int, string> _categoryOptionIds = [];
    private string? _selectedCategoryId;

    public readonly TtsProvider Provider;

    public TtsVoiceRequirementCheckData? RequirementsCheckData
    {
        get => _requirementsCheckData;
        set
        {
            if (_requirementsCheckData == value)
                return;

            _requirementsCheckData = value;
            foreach (var child in CategoryEntriesContainer.Children)
            {
                if (child is not TtsVoiceSelectorCategoryEntry entry)
                    continue;

                entry.RequirementsCheckData = value;
            }

            RefreshSearchState();
        }
    }
    private TtsVoiceRequirementCheckData? _requirementsCheckData;

    public TtsProviderVoiceSelectorWindow(TtsProvider provider, TtsVoiceRequirementCheckData? checkData = null)
    {
        RobustXamlLoader.Load(this);

        _tts = IoCManager.Resolve<IEntitySystemManager>().GetEntitySystem<TtsSystem>();

        Provider = provider;
        _requirementsCheckData = checkData;

        Title = Loc.GetString("ui-tts-provider-voice-selector-window-title", ("providerName", Provider.ToString()));
        SearchLineEdit.OnTextChanged += _ => RefreshSearchState();
        OnlyAvailableCheckBox.OnToggled += _ => RefreshSearchState();
        CategoryOptionButton.OnItemSelected += args =>
        {
            CategoryOptionButton.SelectId(args.Id);
            _selectedCategoryId = _categoryOptionIds.GetValueOrDefault(args.Id);
            RefreshSearchState();
        };

        Refresh();
    }

    public void Refresh()
    {
        CategoryEntriesContainer.RemoveAllChildren();

        var sortedCategories = _tts.EnumerateProviderVoiceCategories(Provider)
            .Where(x => x.Value.Any(v => !v.EditorHidden))
            .OrderByDescending(x => x.Key.SortPriority)
            .ThenBy(x => GetPlainCategoryName(x.Key))
            .ToList();

        RefreshCategoryOptions(sortedCategories.Select(x => x.Key));

        foreach (var (category, voices) in sortedCategories)
        {
            var entry = new TtsVoiceSelectorCategoryEntry(category, voices)
            {
                RequirementsCheckData = _requirementsCheckData
            };
            entry.OnVoiceSelected += voice => OnVoiceSelected?.Invoke(voice);

            CategoryEntriesContainer.AddChild(entry);
        }

        RefreshSearchState();
    }

    private void RefreshCategoryOptions(IEnumerable<TtsVoiceCategoryPrototype> categories)
    {
        CategoryOptionButton.Clear();
        _categoryOptionIds.Clear();

        CategoryOptionButton.AddItem(Loc.GetString("ui-tts-provider-voice-selector-window-all-categories"), AllCategoriesOptionId);

        var nextId = AllCategoriesOptionId + 1;
        var selectedId = AllCategoriesOptionId;
        foreach (var category in categories)
        {
            var id = nextId++;
            _categoryOptionIds[id] = category.ID;
            CategoryOptionButton.AddItem(GetPlainCategoryName(category), id);

            if (category.ID == _selectedCategoryId)
                selectedId = id;
        }

        CategoryOptionButton.SelectId(selectedId);
        _selectedCategoryId = _categoryOptionIds.GetValueOrDefault(selectedId);
    }

    private static string GetPlainCategoryName(TtsVoiceCategoryPrototype category)
    {
        return FormattedMessage.RemoveMarkupPermissive(category.LocalizedName);
    }

    private void RefreshSearchState()
    {
        var searchText = SearchLineEdit.Text.Trim();
        var onlyAvailable = OnlyAvailableCheckBox.Pressed;

        var totalVisible = 0;
        foreach (var child in CategoryEntriesContainer.Children)
        {
            if (child is not TtsVoiceSelectorCategoryEntry categoryEntry)
                continue;

            var categoryPassFilter = _selectedCategoryId == null || categoryEntry.Category.ID == _selectedCategoryId;
            var categoryPassSearch = string.IsNullOrEmpty(searchText) ||
                GetPlainCategoryName(categoryEntry.Category).Contains(searchText, StringComparison.CurrentCultureIgnoreCase);

            var anyCategoryVoiceVisible = false;
            foreach (var categoryChild in categoryEntry.VoiceEntriesContainer.Children)
            {
                if (categoryChild is not TtsVoiceSelectorEntry voiceEntry)
                    continue;

                var voicePassSearch = categoryPassSearch ||
                    voiceEntry.Voice.ID.Contains(searchText, StringComparison.OrdinalIgnoreCase) ||
                    voiceEntry.Voice.LocalizedName.Contains(searchText, StringComparison.CurrentCultureIgnoreCase);

                var voiceVisible = categoryPassFilter && voicePassSearch && (!onlyAvailable || !voiceEntry.Locked);
                voiceEntry.Visible = voiceVisible;

                if (voiceVisible)
                {
                    anyCategoryVoiceVisible = true;
                    totalVisible++;
                }
            }

            categoryEntry.Visible = anyCategoryVoiceVisible;
        }

        // the first visible category should not have a top margin
        var firstVisible = true;
        foreach (var child in CategoryEntriesContainer.Children)
        {
            if (child is not TtsVoiceSelectorCategoryEntry { Visible: true } entry)
                continue;

            entry.Margin = firstVisible ? new Thickness(0) : new Thickness(0, BetweenCategoriesMargin, 0, 0);
            firstVisible = false;
        }

        CountLabel.Text = Loc.GetString("ui-tts-provider-voice-selector-window-count", ("count", totalVisible));
        EmptyLabel.Visible = totalVisible == 0;
    }
}
