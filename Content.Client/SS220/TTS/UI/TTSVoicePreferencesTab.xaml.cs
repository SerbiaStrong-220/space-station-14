using Content.Client.Administration.UI.CustomControls;
using Content.Shared.SS220.TTS;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Input;
using Robust.Shared.Timing;
using System.Numerics;

namespace Content.Client.SS220.TTS.UI;

[GenerateTypedNameReferences]
public sealed partial class TTSVoicePreferencesTab : BoxContainer
{
    [Dependency] private IUserInterfaceManager _uiManager = default!;

    public TTSVoicePreferences VoicePreferences { get; private set; }

    private EntryDragData? _entryDragData;

    public TTSVoicePreferencesTab() : this(null) { }

    public TTSVoicePreferencesTab(TTSVoicePreferences? preferences = null)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        preferences ??= [];
        FillWithAllProviders(preferences);

        VoicePreferences = preferences;
        Refresh();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        UpdateDraggedEntryPosition();
    }

    public void Refresh()
    {
        Content.DisposeAllChildren();

        var first = true;
        foreach (var (provider, protoId) in VoicePreferences)
        {
            if (first)
                first = false;
            else
                Content.AddChild(new HSeparator());

            var entry = new TTSVoicePreferencesTabEntry(provider, protoId);
            entry.OnKeyBindDown += args => OnEntryKeyBindDown(entry, args);
            // entry.OnKeyBindUp += args => OnEntryKeyBindUp(entry, args);
            Content.AddChild(entry);
        }
    }

    private void OnEntryKeyBindDown(TTSVoicePreferencesTabEntry entry, GUIBoundKeyEventArgs args)
    {
        if (args.Function != EngineKeyFunctions.UIClick)
            return;

        StartDragEntry(entry);
    }

    private void OnEntryKeyBindUp(TTSVoicePreferencesTabEntry entry, GUIBoundKeyEventArgs args)
    {
        if (args.Function != EngineKeyFunctions.UIClick)
            return;

        StopDragEntry();
    }

    public void SetPreferences(TTSVoicePreferences pref)
    {
        VoicePreferences = pref;
        Refresh();
    }

    private void StartDragEntry(TTSVoicePreferencesTabEntry entry)
    {
        // StopDragEntry();

        if (_entryDragData != null)
            return;

        var clone = entry.Clone();
        clone.VerticalAlignment = VAlignment.Top;
        entry.DimOverlay.Visible = true;

        _entryDragData = new()
        {
            DraggedEntry = entry,
            DraggedEntryClone = clone
        };

        DragedEntryContainer.AddChild(clone);
    }

    private void StopDragEntry()
    {
        if (_entryDragData is not { } data)
            return;

        data.DraggedEntry.DimOverlay.Visible = false;
        DragedEntryContainer.RemoveChild(data.DraggedEntryClone);

        _entryDragData = null;
    }

    private void UpdateDraggedEntryPosition()
    {
        if (_entryDragData is not { } data)
            return;

        var entry = data.DraggedEntryClone;

        var containerHeight = DragedEntryContainer.Height;
        var entryHeight = entry.Height;
        var entryHalfHeight = entryHeight / 2;
        var maxMargin = containerHeight - entryHeight;

        var globalMousePos = _uiManager.MousePositionScaled.Position;
        var delta = globalMousePos - GlobalPosition;

        LayoutContainer.SetPosition(entry, new Vector2(0, (delta.Y - entryHalfHeight) * UIScale));

        //var margin = Math.Clamp(delta.Y + entryHalfHeight, 0, maxMargin);
        //entry.Margin = new Thickness(0, margin, 0, 0);
    }

    private static void FillWithAllProviders(TTSVoicePreferences pref)
    {
        foreach (var (provider, protoId) in SharedTTSManager.DefaultVoicePreferences)
            pref.Add(provider, protoId);
    }

    private struct EntryDragData
    {
        public TTSVoicePreferencesTabEntry DraggedEntry;
        public TTSVoicePreferencesTabEntry DraggedEntryClone;
    }
}
