[GenerateTypedNameReferences]
public sealed partial class SurgeryPuppetBox : Control
{
    [Dependency] private IEntityManager _entityManager = default!;
    [Dependency] private IPrototypeManager _prototypeManager = default!;

    private const string TexturePath = "/Textures/SS220/Interface/Surgery/puppet";

    private static readonly Color OngoingSurgeryTint = Color.FromHex("#FFA500");
    private static readonly Color ModerateTraumaTint = Color.FromHex("#FFCC44");
    private static readonly Color SevereTraumaTint = Color.FromHex("#FF5555");
    private static readonly Color HealthyZoneTint = Color.FromHex("#4AC4FF");
    private static readonly Vector2 CompactCropOffset = new(11f, 5f);
    private static readonly Vector2 CompactBaseSize = new(19f, 31f);
    private static readonly IReadOnlySet<SurgeryPuppetPart> EmptyZones = new HashSet<SurgeryPuppetPart>();
    private static readonly SurgeryPuppetPart[] HeadSubZones =
    {
        SurgeryPuppetPart.Head,
        SurgeryPuppetPart.Eyes,
        SurgeryPuppetPart.Mouth,
    };

    private Vector2 _scale = new Vector2(1f);
    private SurgeryPuppetPart? _selectedPart;
    private bool _interactive = true;
    private bool _showBackground = true;

    private SortedDictionary<SurgeryPuppetPart, TextureRect> _parts = new();
    private SortedDictionary<SurgeryPuppetPart, TextureRect> _highlightedPart = new();
    private List<PuppetButton> _partButtons = new();
    private Dictionary<SurgeryPuppetPart, PuppetButton> _partButtonMap = new();
    private Vector2 _baseTextureSize = new(42f, 42f);

    /// <summary>
    /// First argument is current part, second is previous
    /// </summary>
    public event Action<SurgeryPuppetPart?, SurgeryPuppetPart?>? SelectedPartChanged;

    public Vector2 Scale
    {
        get => _scale;
        set
        {
            _scale = value;
            ResizeAll();
        }
    }

    public SurgeryPuppetPart? SelectedPart
    {
        get => _selectedPart;
        set
        {
            _selectedPart = HighlightPuppetPart(value);
        }
    }

    /// <summary>
    /// Enables selecting body zones on click. Disabled for read-only indicators (HUD and Health Analyzer).
    /// </summary>
    public bool Interactive
    {
        get => _interactive;
        set
        {
            if (_interactive == value)
                return;

            _interactive = value;
            ApplyInteractivity();
        }
    }

    /// <summary>
    /// Controls visibility of the surgical tablet background and side labels.
    /// When disabled, crops to the body silhouette and tints healthy zones blue.
    /// </summary>
    public bool ShowBackground
    {
        get => _showBackground;
        set
        {
            if (_showBackground == value)
                return;

            _showBackground = value;
            ResizeAll();
            if (!_showBackground)
                UpdateZoneStates(EmptyZones, EmptyZones, EmptyZones);
        }
    }

    public SurgeryPuppetBox()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
    }

    public void Initialize()
    {
        foreach (var part in Enum.GetValues<SurgeryPuppetPart>())
        {
            var textPart = MakePuppetPartButton(part, _parts, GetPuppetPartTexturePath);

            if (textPart != null)
                this.AddChild(textPart);

            textPart = MakePuppetPartButton(part, _highlightedPart, GetBodyPartelectedTexturePath);

            if (textPart != null)
            {
                this.AddChild(textPart);
                textPart.Visible = false;
            }

            var button = MakePuppetPartButton(part);

            if (button != null)
            {
                AddChild(button);
                _partButtons.Add(button);
                _partButtonMap[part] = button;
            }
        }

        ResizeAll();
        if (!_showBackground)
            UpdateZoneStates(EmptyZones, EmptyZones, EmptyZones);
    }

    private Control? MakePuppetPartButton(SurgeryPuppetPart part, SortedDictionary<SurgeryPuppetPart, TextureRect> bodyPartTexture, Func<SurgeryPuppetPart, string?> pathSpecifier)
    {
        var partTexturePath = pathSpecifier(part);

        if (partTexturePath == null)
            return null;

        var texture = new TextureRect
        {
            Stretch = TextureRect.StretchMode.Keep,
            TexturePath = partTexturePath
        };

        bodyPartTexture.Add(part, texture);

        return texture;
    }

    private PuppetButton? MakePuppetPartButton(SurgeryPuppetPart part)
    {
        var offset = GetPartOffset(part);
        var size = GetPartSize(part);

        if (offset == null || size == null)
            return null;

        var thickness = GetPartThickness(offset.Value, size.Value, Scale, _baseTextureSize);

        var button = new PuppetButton
        {
            Part = part,
            SetSize = size.Value * Scale,
            Margin = thickness,
            ToolTip = GetPartDisplayName(part),
        };

        ApplyButtonInteractivity(button);

        button.OnPressed += (_) =>
        {
            if (!_interactive)
                return;

            SelectedPart = part;
        };

        return button;
    }

    private void ApplyInteractivity()
    {
        foreach (var button in _partButtons)
        {
            ApplyButtonInteractivity(button);
        }

        if (_interactive)
        {
            ResetHeadSubOverlayIfUnselected(SurgeryPuppetPart.Eyes);
            ResetHeadSubOverlayIfUnselected(SurgeryPuppetPart.Mouth);
        }
    }

    private void ApplyButtonInteractivity(PuppetButton button)
    {
        button.MuteSounds = !_interactive;
        button.DefaultCursorShape = _interactive ? CursorShape.Pointer : CursorShape.Arrow;
    }

    private void ResetHeadSubOverlayIfUnselected(SurgeryPuppetPart subPart)
    {
        if (_selectedPart == subPart || !_highlightedPart.TryGetValue(subPart, out var overlay))
            return;

        overlay.Visible = false;
        overlay.ModulateSelfOverride = null;
    }

    private void ResizeAll()
    {
        var cropOffset = _showBackground ? Vector2.Zero : CompactCropOffset;
        var activeBaseSize = _showBackground ? _baseTextureSize : CompactBaseSize;
        var textureMargin = _showBackground
            ? default
            : new Thickness(
                -cropOffset.X * _scale.X,
                -cropOffset.Y * _scale.Y,
                -(_baseTextureSize.X - cropOffset.X - activeBaseSize.X) * _scale.X,
                -(_baseTextureSize.Y - cropOffset.Y - activeBaseSize.Y) * _scale.Y);

        Background.Visible = _showBackground;
        Background.TextureScale = _scale;
        RectClipContent = !_showBackground;

        foreach (var texture in _parts.Values)
        {
            texture.TextureScale = _scale;
            texture.Margin = textureMargin;
        }
        foreach (var texture in _highlightedPart.Values)
        {
            texture.TextureScale = _scale;
            texture.Margin = textureMargin;
        }
        foreach (var button in _partButtons)
        {
            var size = GetPartSize(button.Part);
            var offset = GetPartOffset(button.Part);

            if (size == null || offset == null)
                continue;

            button.Margin = GetPartThickness(offset.Value - cropOffset, size.Value, Scale, activeBaseSize);
            button.SetSize = size.Value * Scale;
        }

        var scaledSize = activeBaseSize * _scale;
        MinSize = scaledSize;
        SetSize = scaledSize;
    }

    /// <summary>
    /// I hope no one else will need to give a fck what happens here. God bless new med.
    /// </summary>
    private SurgeryPuppetPart? HighlightPuppetPart(SurgeryPuppetPart? puppetPartClicked)
    {
        var newHighlightPart = puppetPartClicked;
        switch (puppetPartClicked)
        {
            case SurgeryPuppetPart.Head:
                switch (_selectedPart)
                {
                    case SurgeryPuppetPart.Head:
                        newHighlightPart = SurgeryPuppetPart.Eyes;
                        break;
                    case SurgeryPuppetPart.Eyes:
                        newHighlightPart = SurgeryPuppetPart.Mouth;
                        break;
                    case SurgeryPuppetPart.Mouth:
                        newHighlightPart = SurgeryPuppetPart.Head;
                        break;
                    default:
                        break;
                }
                break;
            default:
                break;
        }

        if (newHighlightPart == _selectedPart)
            return _selectedPart;

        if (_selectedPart != null)
            RemoveHighlight(_selectedPart.Value);

        if (newHighlightPart != null)
            MakeHighlighted(newHighlightPart.Value);

        SelectedPartChanged?.Invoke(newHighlightPart, _selectedPart);

        return newHighlightPart;
    }

    private void MakeHighlighted(SurgeryPuppetPart part)
    {
        if (_highlightedPart.TryGetValue(part, out var newTextureControl))
            newTextureControl.Visible = true;
        if (_parts.TryGetValue(part, out var oldTextureControl))
            oldTextureControl.Visible = false;
    }

    private void RemoveHighlight(SurgeryPuppetPart part)
    {
        if (_highlightedPart.TryGetValue(part, out var newTextureControl))
            newTextureControl.Visible = false;
        if (_parts.TryGetValue(part, out var oldTextureControl))
            oldTextureControl.Visible = true;
    }

    public (HashSet<SurgeryPuppetPart> TraumaZones, HashSet<SurgeryPuppetPart> OngoingZones) UpdateFromTarget(EntityUid? target)
    {
        var moderateZones = new HashSet<SurgeryPuppetPart>();
        var severeZones = new HashSet<SurgeryPuppetPart>();
        var ongoingZones = new HashSet<SurgeryPuppetPart>();
        var zoneEntries = new Dictionary<SurgeryPuppetPart, List<string>>();

        if (target != null &&
            _entityManager.TryGetComponent<PathologyHolderComponent>(target, out var holder) &&
            holder.LifeStage < ComponentLifeStage.Stopping)
        {
            foreach (var (pathologyId, instanceData) in holder.ActivePathologies)
            {
                if (!_prototypeManager.Resolve(pathologyId, out var pathologyProto))
                    continue;

                if (pathologyProto.TargetZone is not { } zone)
                    continue;

                var isSevere = pathologyProto.IsSevere ||
                               instanceData.Level > 0 ||
                               instanceData.StackCount > SharedPathologySystem.OneStack;

                if (isSevere)
                    severeZones.Add(zone);
                else
                    moderateZones.Add(zone);

                var label = Loc.GetString(pathologyProto.Name);
                if (instanceData.StackCount > SharedPathologySystem.OneStack)
                    label = Loc.GetString("pathology-hud-entry-with-stack", ("name", label), ("count", instanceData.StackCount));

                if (!zoneEntries.TryGetValue(zone, out var entries))
                {
                    entries = new List<string>();
                    zoneEntries[zone] = entries;
                }

                entries.Add(label);
            }
        }

        if (target != null &&
            _entityManager.TryGetComponent<SurgeryPatientComponent>(target, out var patient) &&
            patient.LifeStage < ComponentLifeStage.Stopping)
        {
            foreach (var (graphId, node) in patient.OngoingSurgeries)
            {
                if (!_prototypeManager.Resolve(graphId, out var graphProto))
                    continue;

                if (node == graphProto.End)
                    continue;

                ongoingZones.Add(graphProto.TargetPart);
            }
        }

        UpdateZoneStates(moderateZones, severeZones, ongoingZones);
        UpdateTooltips(zoneEntries);

        var allTraumaZones = new HashSet<SurgeryPuppetPart>(moderateZones);
        allTraumaZones.UnionWith(severeZones);
        return (allTraumaZones, ongoingZones);
    }

    public void UpdateZoneStates(IReadOnlySet<SurgeryPuppetPart> traumaZones, IReadOnlySet<SurgeryPuppetPart> ongoingSurgeryZones)
    {
        UpdateZoneStates(EmptyZones, traumaZones, ongoingSurgeryZones);
    }

    public void UpdateZoneStates(
        IReadOnlySet<SurgeryPuppetPart> moderateTraumaZones,
        IReadOnlySet<SurgeryPuppetPart> severeTraumaZones,
        IReadOnlySet<SurgeryPuppetPart> ongoingSurgeryZones)
    {
        var includeHeadSubZones = Interactive;
        Color? healthyTint = _showBackground ? null : HealthyZoneTint;

        foreach (var (part, texture) in _parts)
        {
            texture.ModulateSelfOverride = ResolveZoneTint(
                part,
                moderateTraumaZones,
                severeTraumaZones,
                ongoingSurgeryZones,
                includeHeadSubZones,
                healthyTint);
        }

        if (!Interactive)
        {
            UpdateHeadSubOverlay(SurgeryPuppetPart.Eyes, moderateTraumaZones, severeTraumaZones, ongoingSurgeryZones);
            UpdateHeadSubOverlay(SurgeryPuppetPart.Mouth, moderateTraumaZones, severeTraumaZones, ongoingSurgeryZones);
        }
    }

    private void UpdateHeadSubOverlay(
        SurgeryPuppetPart subPart,
        IReadOnlySet<SurgeryPuppetPart> moderateTraumaZones,
        IReadOnlySet<SurgeryPuppetPart> severeTraumaZones,
        IReadOnlySet<SurgeryPuppetPart> ongoingSurgeryZones)
    {
        if (!_highlightedPart.TryGetValue(subPart, out var overlay))
            return;

        var tint = ResolveZoneTint(subPart, moderateTraumaZones, severeTraumaZones, ongoingSurgeryZones, false, null);
        overlay.Visible = tint != null;
        overlay.ModulateSelfOverride = tint;
    }

    private void UpdateTooltips(IReadOnlyDictionary<SurgeryPuppetPart, List<string>> zoneEntries)
    {
        foreach (var (part, button) in _partButtonMap)
        {
            if (part == SurgeryPuppetPart.Head)
            {
                button.ToolTip = BuildHeadTooltip(zoneEntries);
                continue;
            }

            button.ToolTip = BuildZoneTooltip(part, zoneEntries);
        }
    }

    private string BuildHeadTooltip(IReadOnlyDictionary<SurgeryPuppetPart, List<string>> zoneEntries)
    {
        var sb = new StringBuilder();

        foreach (var headZone in HeadSubZones)
        {
            if (zoneEntries.TryGetValue(headZone, out var entries))
                AppendTooltipSection(sb, headZone, entries);
        }

        return sb.Length > 0 ? sb.ToString() : GetPartDisplayName(SurgeryPuppetPart.Head);
    }

    private string BuildZoneTooltip(SurgeryPuppetPart part, IReadOnlyDictionary<SurgeryPuppetPart, List<string>> zoneEntries)
    {
        if (!zoneEntries.TryGetValue(part, out var entries) || entries.Count == 0)
            return GetPartDisplayName(part);

        var sb = new StringBuilder();
        AppendTooltipSection(sb, part, entries);
        return sb.ToString();
    }

    private static void AppendTooltipSection(StringBuilder sb, SurgeryPuppetPart zone, IReadOnlyList<string> entries)
    {
        if (entries.Count == 0)
            return;

        if (sb.Length > 0)
            sb.AppendLine();

        sb.Append(GetPartDisplayName(zone));
        sb.Append(':');
        foreach (var entry in entries)
        {
            sb.AppendLine();
            sb.Append("- ");
            sb.Append(entry);
        }
    }

    private static string GetPartDisplayName(SurgeryPuppetPart part)
    {
        return Loc.GetString($"surgery-puppet-part-{part.ToString().ToLowerInvariant()}");
    }

    private static Color? ResolveZoneTint(
        SurgeryPuppetPart part,
        IReadOnlySet<SurgeryPuppetPart> moderateTraumaZones,
        IReadOnlySet<SurgeryPuppetPart> severeTraumaZones,
        IReadOnlySet<SurgeryPuppetPart> ongoingSurgeryZones,
        bool includeHeadSubZones,
        Color? healthyTint)
    {
        var checkHeadSub = includeHeadSubZones && part == SurgeryPuppetPart.Head;

        if (ongoingSurgeryZones.Contains(part) ||
            (checkHeadSub && (ongoingSurgeryZones.Contains(SurgeryPuppetPart.Eyes) ||
                              ongoingSurgeryZones.Contains(SurgeryPuppetPart.Mouth))))
            return OngoingSurgeryTint;

        if (severeTraumaZones.Contains(part) ||
            (checkHeadSub && (severeTraumaZones.Contains(SurgeryPuppetPart.Eyes) ||
                              severeTraumaZones.Contains(SurgeryPuppetPart.Mouth))))
            return SevereTraumaTint;

        if (moderateTraumaZones.Contains(part) ||
            (checkHeadSub && (moderateTraumaZones.Contains(SurgeryPuppetPart.Eyes) ||
                              moderateTraumaZones.Contains(SurgeryPuppetPart.Mouth))))
            return ModerateTraumaTint;

        return healthyTint;
    }

