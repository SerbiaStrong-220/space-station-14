namespace Content.Client.SS220.Surgery.NodeGraphUi;

[GenerateTypedNameReferences]
public sealed partial class EdgeDescription : BoxContainer
{
    [Dependency] private IPrototypeManager _prototypeManager = default!;
    [Dependency] private IEntityManager _entityManager = default!;

    private readonly SurgeryGraphSystem _surgeryGraph = default!;
    private readonly SharedSurgerySystem _surgery = default!;

    private SurgeryGraphEdge? _edge;

    private static readonly StyleBoxFlat AvailablePlate = new()
    {
        BackgroundColor = Color.FromHex("#33354A"),
        BorderColor = Color.FromHex("#44475F"),
        BorderThickness = new Thickness(1),
    };

    private static readonly StyleBoxFlat UnavailablePlate = new()
    {
        BackgroundColor = Color.FromHex("#26272D"),
        BorderColor = Color.FromHex("#303139"),
        BorderThickness = new Thickness(1),
    };

    private static readonly Color UnavailableText = Color.FromHex("#8A8A92");

    private static readonly LocId EdgeName = "operation-description-edge-to";
    private static readonly LocId EdgeNameSameNode = "operation-description-edge-to-same-node";

    private static readonly LocId OperationDescriptionConditionSection = "operation-description-condition-section-name";
    private static readonly LocId OperationDescriptionActionDescriptions = "operation-description-action-description-section-name";

    public EdgeDescription()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _surgeryGraph = _entityManager.System<SurgeryGraphSystem>();
        _surgery = _entityManager.System<SharedSurgerySystem>();

        SetAvailable(true);
    }

    public void SetEdgeInfo(SurgeryGraphEdge edge, string nodeId)
    {
        _edge = edge;

        var edgeName = edge.Target != nodeId
            ? Loc.GetString(EdgeName, ("to", Loc.GetString(edge.Target)), ("edgeName", Loc.GetString(edge.EdgeTooltip)))
            : Loc.GetString(EdgeNameSameNode, ("edgeName", Loc.GetString(edge.EdgeTooltip)));

        EdgeNameLabel.SetMarkup(edgeName);

        AddDescriptionInfo(edge);
        AddConditionInfo(edge);
    }

    /// <summary>
    /// Greys the plate out if the patient or the surgeon don't meet the step's requirements.
    /// The tools and the organ in hand are not checked: taking the right one is up to the surgeon.
    /// </summary>
    public void UpdateAvailability(EntityUid patient, EntityUid performer)
    {
        if (_edge is null)
            return;

        SetAvailable(MeetsRequirements(_surgeryGraph.GetVisibilityRequirements(_edge), patient, performer)
            && MeetsRequirements(_surgeryGraph.GetRequirements(_edge), patient, performer));
    }

    public void SetAvailable(bool available)
    {
        Plate.PanelOverride = available ? AvailablePlate : UnavailablePlate;
        PlateContent.Modulate = available ? Color.White : UnavailableText;
    }

    private bool MeetsRequirements(IReadOnlyList<SurgeryGraphRequirement> requirements, EntityUid patient, EntityUid performer)
    {
        foreach (var requirement in requirements)
        {
            // the compatible organ check reads the organ held in hand, the same as a tool
            if (requirement.Subject == SurgeryGraphRequirementSubject.Used || requirement is CompatibleOrganRequirement)
                continue;

            var subject = _surgery.ResolveRequirementSubject(requirement, performer, patient, null);
            if (!requirement.SatisfiesRequirements(subject, performer, null, _entityManager))
                return false;
        }

        return true;
    }

    private void AddDescriptionInfo(SurgeryGraphEdge edge)
    {
        var actionLocIds = _surgeryGraph.GetActionsLocIds(edge);
        if (actionLocIds.Count == 0)
            return;

        var builder = new StringBuilder();
        builder.AppendJoin('\n', actionLocIds.Select(x => Loc.GetString(x)));
        EdgeActionDescriptionsLabel.SetMarkup(builder.ToString());
    }

    private void AddConditionInfo(SurgeryGraphEdge edge)
    {
        var visibilityRequirements = _surgeryGraph.GetVisibilityRequirements(edge);
        var surgeryRequirements = _surgeryGraph.GetRequirements(edge);
        if (surgeryRequirements.Count == 0 && visibilityRequirements.Count == 0)
            return;

        // visibility requirements are conditions too (e.g. holding the organ to insert), repair steps repeat them in requirements
        var descriptions = new List<string>();
        foreach (var requirement in visibilityRequirements)
        {
            AddUniqueDescription(descriptions, requirement);
        }

        foreach (var requirement in surgeryRequirements)
        {
            AddUniqueDescription(descriptions, requirement);
        }

        var builder = new StringBuilder();
        builder.Append(Loc.GetString(OperationDescriptionConditionSection));
        foreach (var description in descriptions)
        {
            builder.AppendLine();
            builder.Append(description);
        }

        this.TooltipSupplier = CreateRichTooltip;
        this.ToolTip = builder.ToString();
    }

    private void AddUniqueDescription(List<string> descriptions, SurgeryGraphRequirement requirement)
    {
        var description = requirement.RequirementDescription(_prototypeManager, _entityManager);
        if (!descriptions.Contains(description))
            descriptions.Add(description);
    }

    private Tooltip CreateRichTooltip(Control hovered)
    {
        var tooltip = new Tooltip()
        {
            Tracking = hovered.TrackingTooltip,
        };

        if (FormattedMessage.TryFromMarkup(hovered.ToolTip ?? "", out var message))
        {
            tooltip.SetMessage(message);
        }
        else
        {
            tooltip.Text = hovered.ToolTip;
        }

        return tooltip;
    }
}
