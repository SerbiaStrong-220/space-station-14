using Content.Client.UserInterface.Controls;
using Content.Shared.SS220.Surgery.Components;
using Content.Shared.SS220.Surgery.Graph;
using Content.Shared.SS220.Surgery.Systems;
using Robust.Client.AutoGenerated;
using Robust.Client.Player;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client.SS220.Surgery.BodyAnalyzerUi;

[GenerateTypedNameReferences]
public sealed partial class BodyAnalyzerMenu : FancyWindow
{
    [Dependency] private IEntityManager _entityManager = default!;
    [Dependency] private IPlayerManager _player = default!;

    private SurgeryPatientAnalyzer _surgeryPatientAnalyzer = default!;

    /// <summary>
    /// Operations going on the patient, while there are any the steps stay locked on one of them.
    /// </summary>
    private readonly List<ProtoId<SurgeryGraphPrototype>> _ongoing = new();

    /// <summary>
    /// The disk of the computer the shown steps were made with.
    /// </summary>
    private EntityUid? _shownDisk;

    public BodyAnalyzerMenu()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _surgeryPatientAnalyzer = _entityManager.System<SurgeryPatientAnalyzer>();

        OperationList.OnSurgeryClicked += (id, pressed) =>
        {
            OperationDescription.ShowDescription(id, force: true);
            OperationDescription.DataLocked = pressed || _ongoing.Count > 0;

            if (_ongoing.Count > 0)
                OperationList.SetOngoing(_ongoing, id);
        };

        OperationList.OnSurgeryHovered += (id) =>
        {
            OperationDescription.ShowDescription(id);
        };
    }

    public void ChangeTarget(EntityUid? target, bool tableNotLinked = false)
    {
        // a disk put into or taken out of the computer while the UI is open
        if (UpdateShownDisk())
            OperationDescription.Refresh();

        if (target is not { } patient)
        {
            if (tableNotLinked)
                TreatmentSuggestion.ShowTableNotLinked();
            else
                TreatmentSuggestion.ShowTargetlessSuggestion();

            PatientStatus.ShowUnknownStatus();
            UpdateOngoing(null);
            return;
        }

        var status = _surgeryPatientAnalyzer.GetStatus(patient);
        PatientStatus.ShowStatus(status);
        UpdateOngoing(patient);
        if (_player.LocalEntity is { } performer)
            OperationDescription.UpdateNodeShowTarget(patient, performer);

        TreatmentSuggestion.ShowSuggestion(_surgeryPatientAnalyzer.GetTreatmentRecommendation(status));
    }

    public void UpdatePerformer(EntityUid analyzer, bool tableNotLinked = false)
    {
        OperationDescription.Analyzer = analyzer;
        UpdateShownDisk();

        OperationList.MakeList(false);
        OperationList.SetOngoing(_ongoing, OperationDescription.CurrentOperation);

        if (tableNotLinked)
            TreatmentSuggestion.ShowTableNotLinked();
        else
            TreatmentSuggestion.ShowTargetlessSuggestion();

        PatientStatus.ShowUnknownStatus();
    }

    /// <returns>True if the disk in the computer changed since the last call</returns>
    private bool UpdateShownDisk()
    {
        if (!_entityManager.TryGetComponent<OperatingComputerComponent>(OperationDescription.Analyzer, out var computer))
            return false;

        _entityManager.System<SharedSurgerySystem>().TryGetDisk((OperationDescription.Analyzer, computer), out var disk);
        if (disk?.Owner == _shownDisk)
            return false;

        _shownDisk = disk?.Owner;
        return true;
    }

    private void UpdateOngoing(EntityUid? patient)
    {
        var wasOngoing = _ongoing.Count > 0;
        _ongoing.Clear();
        if (_entityManager.TryGetComponent<SurgeryPatientComponent>(patient, out var surgeryPatient))
            _ongoing.AddRange(surgeryPatient.OngoingSurgeries.Keys);

        if (_ongoing.Count > 0)
        {
            if (OperationDescription.CurrentOperation is not { } shown || !_ongoing.Contains(shown))
                OperationDescription.ShowDescription(_ongoing[0], force: true);

            OperationDescription.DataLocked = true;
        }
        else if (wasOngoing)
        {
            OperationDescription.DataLocked = false;
            OperationList.SetAllSurgeryButtonsPress(false);
        }

        OperationList.SetOngoing(_ongoing, OperationDescription.CurrentOperation);
    }
}
