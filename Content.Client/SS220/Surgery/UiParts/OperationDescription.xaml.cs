using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client.SS220.Surgery.UiParts;

[GenerateTypedNameReferences]
public sealed partial class OperationDescription : Control
{
    [Dependency] private IPrototypeManager _prototypeManager = default!;
    [Dependency] private IEntityManager _entityManager = default!;

    private bool _dataLocked = false;
    public bool DataLocked
    {
        get => _dataLocked;
        set
        {
            _dataLocked = value;
            LockIcon.Visible = value;
        }
    }

    private ProtoId<SurgeryGraphPrototype>? _currentOperation = null;
    public ProtoId<SurgeryGraphPrototype>? CurrentOperation => _currentOperation;

    /// <summary>
    /// The entity of the UI, its disk opens the disk steps.
    /// </summary>
    public EntityUid Analyzer;

    public OperationDescription()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
    }

    /// <summary>
    /// Marks the node the patient's shown operation is at, if it goes on.
    /// </summary>
    public void UpdateNodeShowTarget(EntityUid patient, EntityUid performer)
    {
        string? currentNode = null;
        if (_currentOperation is { } operation
            && _entityManager.TryGetComponent<SurgeryPatientComponent>(patient, out var surgeryPatient))
            surgeryPatient.OngoingSurgeries.TryGetValue(operation, out currentNode);

        foreach (var child in OperationContainer.Children)
        {
            if (child is not OperationNodeLabel label)
                continue;

            label.SetActive(currentNode == label.NodeId, patient, performer);
        }
    }

    public void ShowDescription(ProtoId<SurgeryGraphPrototype>? id, bool force = false)
    {
        this.Visible = true;
        if (id == _currentOperation)
            return;

        if (!force && DataLocked)
            return;

        _currentOperation = id;
        if (!_currentOperation.HasValue)
            return;

        OperationContainer.RemoveAllChildren();

        if (!_prototypeManager.Resolve(id, out var surgeryProto))
            return;

        AddOperationSteps(surgeryProto);
    }

    /// <summary>
    /// Rebuilds the shown steps, e.g. after the disk of the computer changed.
    /// </summary>
    public void Refresh()
    {
        if (!_prototypeManager.Resolve(_currentOperation, out var surgeryProto))
            return;

        OperationContainer.RemoveAllChildren();
        AddOperationSteps(surgeryProto);
    }

    private void AddOperationSteps(SurgeryGraphPrototype graph)
    {
        var nodes = graph.Nodes;

        foreach (var node in nodes)
        {
            var nodeLabel = new OperationNodeLabel();
            nodeLabel.SetNodeInfo(node, Analyzer);

            OperationContainer.AddChild(nodeLabel);
        }
    }
}
