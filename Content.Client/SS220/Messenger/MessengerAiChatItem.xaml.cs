using Content.Client.RichText;
using Content.Client.SS220.Cartridges.Messenger;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.SS220.Messenger;

/// <summary>
/// Button of a chat in the list of the read-only window of the station AI.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class MessengerAiChatItem : Button
{
    /// <param name="preview">Preview of the last message, may contain emoji shortcodes.</param>
    public MessengerAiChatItem(string title, string preview, Color titleColor, Color previewColor)
    {
        RobustXamlLoader.Load(this);

        TitleLabel.Text = title;
        TitleLabel.FontColorOverride = titleColor;
        PreviewLabel.SetMessage(MessengerEmoji.Format(preview), UserFormattableTags.BaseAllowedTags, previewColor);
    }

    public MessengerAiChatItem()
    {
        RobustXamlLoader.Load(this);
    }
}
