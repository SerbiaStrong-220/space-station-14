namespace Content.Client.SS220.Messenger;

/// <summary>
/// Read-only terminal-like window of the station AI with chats of a messenger server.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class MessengerAiWindow : FancyWindow, IPinnableWindow
{
    private static readonly Color BackgroundColor = Color.FromHex("#0a120d");
    private static readonly Color TextColor = Color.FromHex("#7cfc9a");
    private static readonly Color DimTextColor = Color.FromHex("#3f8f58");
    private static readonly Color MessageColor = Color.FromHex("#14402c99");

    private const int MaxPreviewLength = 50;
    private const int ScrollToBottomFrames = 2;
    private static readonly TimeSpan RefreshInterval = TimeSpan.FromSeconds(5);

    /// <summary>
    /// Asks the server for the overview (null) or for the history of a chat.
    /// </summary>
    public event Action<ChatUid?>? OnRequest;

    private MessengerAiViewMessage? _view;
    private TimeSpan _nextRefresh;
    private int _shownMessages;
    private int _scrollToBottomFrames;

    public MessengerAiWindow()
    {
        RobustXamlLoader.Load(this);

        Background.PanelOverride = new StyleBoxFlat { BackgroundColor = BackgroundColor };
        HeaderLabel.FontColorOverride = TextColor;
        ReadOnlyLabel.FontColorOverride = DimTextColor;

        BackButton.OnPressed += _ => Request(null);
        RefreshButton.OnPressed += _ => Request(_view?.OpenedChatId);
        SearchEdit.OnTextChanged += _ => Rebuild();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (_scrollToBottomFrames > 0)
        {
            _scrollToBottomFrames--;
            ContentScroll.SetScrollValue(new Vector2(0, float.MaxValue));
        }

        _nextRefresh -= TimeSpan.FromSeconds(args.DeltaSeconds);

        if (_nextRefresh <= TimeSpan.Zero)
            Request(_view?.OpenedChatId);
    }

    public void SetView(MessengerAiViewMessage view)
    {
        var chatChanged = _view?.OpenedChatId != view.OpenedChatId;

        _view = view;
        Rebuild();

        // follow new messages, but don't throw the reader out of the old ones
        if (view.OpenedChatId != null && (chatChanged || view.Messages.Count > _shownMessages))
            _scrollToBottomFrames = ScrollToBottomFrames;

        _shownMessages = view.Messages.Count;
    }

    private void Request(ChatUid? chatId)
    {
        _nextRefresh = RefreshInterval;
        SearchEdit.Clear();
        OnRequest?.Invoke(chatId);
    }

    private void Rebuild()
    {
        Content.RemoveAllChildren();

        if (_view == null)
            return;

        HeaderLabel.Text = Loc.GetString("messenger-ai-header", ("server", _view.ServerName));
        BackButton.Visible = _view.OpenedChatId != null;

        var search = SearchEdit.Text == "" ? null : SearchEdit.Text.ToLower();

        if (_view.OpenedChatId != null && TryGetChat(_view.OpenedChatId.Value, out var openedChat))
            BuildHistory(openedChat, search);
        else
            BuildChatList(search);
    }

    private bool TryGetChat(ChatUid chatId, out MessengerChat chat)
    {
        foreach (var candidate in _view!.Chats)
        {
            if (candidate.Id != chatId)
                continue;

            chat = candidate;
            return true;
        }

        chat = default!;
        return false;
    }

    private void BuildChatList(string? search)
    {
        var shown = 0;

        foreach (var chat in _view!.Chats)
        {
            var title = ChatTitle(chat);

            if (search != null && !title.ToLower().Contains(search))
                continue;

            var openedId = chat.Id;
            var item = new MessengerAiChatItem(title, LastMessagePreview(chat), TextColor, DimTextColor);

            item.OnPressed += _ => Request(openedId);

            Content.AddChild(item);
            shown++;
        }

        if (shown == 0)
            AddInfoLabel(Loc.GetString("messenger-ai-chats-empty"));
    }

    private void BuildHistory(MessengerChat chat, string? search)
    {
        AddInfoLabel(ChatTitle(chat));

        var messages = new List<MessengerMessage>();

        foreach (var message in _view!.Messages.Values)
        {
            if (message.ChatId == chat.Id && (search == null || message.Text.ToLower().Contains(search)))
                messages.Add(message);
        }

        messages.Sort((a, b) => a.Id.CompareTo(b.Id));

        foreach (var message in messages)
        {
            MessengerMessage? quoted = null;

            if (message.ReplyToId != null)
                _view.Messages.TryGetValue(message.ReplyToId.Value, out quoted);

            Content.AddChild(new MessengerUiMessageItem(message.Text,
                message.Time,
                ContactName(message.FromContactId),
                false,
                MessageColor,
                quoted == null ? null : ContactName(quoted.FromContactId),
                quoted?.Text));
        }

        if (messages.Count == 0)
            AddInfoLabel(Loc.GetString("messenger-ai-no-messages"));
    }

    private void AddInfoLabel(string text)
    {
        Content.AddChild(new Label
        {
            Text = text,
            Align = Label.AlignMode.Center,
            FontColorOverride = DimTextColor,
        });
    }

    /// <summary>
    /// Names of the chat members or just one name for the favorites chat.
    /// </summary>
    private string ChatTitle(MessengerChat chat)
    {
        if (chat.Kind != MessengerChatKind.Contact)
            return chat.Name ?? "";

        var names = new List<string>(chat.MembersId.Count);

        foreach (var memberId in chat.MembersId)
        {
            names.Add(ContactName(memberId));
        }

        names.Sort();

        return string.Join(" / ", names);
    }

    private string ContactName(ContactUid contactId)
    {
        return _view!.ContactNames.TryGetValue(contactId, out var name) && name != ""
            ? name
            : Loc.GetString("messenger-ai-unknown-contact");
    }

    private string LastMessagePreview(MessengerChat chat)
    {
        if (chat.LastMessageId == null || !_view!.Messages.TryGetValue(chat.LastMessageId.Value, out var message))
            return "";

        return MessengerEmoji.Preview($"{ContactName(message.FromContactId)}: {message.Text}", MaxPreviewLength);
    }
}
